# ------------------------------------------------------------- runtime_state record
def record_runtime_state(
    ledger_path: str | Path | None, key: str, value: Any
) -> tuple[bool, str | None]:
    """Write exactly one ``runtime_state`` key; never raise.

    A direct SQLite write is used (not ``ObservationLedger.set_runtime``) so this
    operational note cannot trigger a schema/meta write on a live ledger.
    """
    if ledger_path is None:
        return False, "no ledger path"
    path = Path(ledger_path)
    if not path.is_file():
        return False, f"observation ledger not found: {path}"
    try:
        connection = sqlite3.connect(str(path), timeout=45.0)
    except sqlite3.Error as exc:  # pragma: no cover - unreadable file
        return False, f"{type(exc).__name__}: {exc}"
    try:
        connection.execute("PRAGMA busy_timeout=45000")
        payload = json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)
        connection.execute(
            "INSERT INTO runtime_state(key, value, updated_at) VALUES(?,?,?)"
            " ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at",
            (key, payload, utc_now_iso()),
        )
        connection.commit()
        return True, None
    except sqlite3.Error as exc:
        return False, f"{type(exc).__name__}: {exc}"
    finally:
        try:
            connection.close()
        except sqlite3.Error:  # pragma: no cover
            pass


# --------------------------------------------------------------------- create_backup
def _failure_result(started: float, *, created_at: str, error: str) -> dict[str, Any]:
    return {
        "ok": False,
        "status": "FAILED",
        "verified": False,
        "bundle": None,
        "path": None,
        "ledger": None,
        "bytes": 0,
        "ledger_bytes": 0,
        "created_at": created_at,
        "sha256_manifest": None,
        "manifest": None,
        "verification": None,
        "counts": {},
        "first_seen": {},
        "cache_included": False,
        "prospective_included": False,
        "retention": {"kept": 0, "pruned": 0},
        "runtime_state_recorded": False,
        "runtime_state_error": None,
        "duration_ms": int((time.monotonic() - started) * 1000),
        "error": error,
    }


def create_backup(
    ledger_path: str | Path | None = None,
    dest_dir: str | Path | None = None,
    include_raw_cache: bool = False,
    include_prospective: bool = True,
    label: str | None = None,
    *,
    prune_on_create: bool = False,
    record_last_backup: bool = True,
) -> dict[str, Any]:
    """Create one verified, atomically published backup bundle.

    Returns a machine-readable dict (never raises for operational failures).  The
    bundle is **not** OK until :func:`verify_backup` passed on the published copy;
    otherwise the result is ``status="UNVERIFIED"`` / ``"FAILED"``.

    ``record_last_backup=False`` is used by the restore-drill workflow: a bundle
    written into a throwaway work directory must never replace the ledger's
    "last production backup" record (drills record ``last_restore_drill`` instead).
    """
    started = time.monotonic()
    created_at = utc_now_iso()
    source = Path(ledger_path) if ledger_path is not None else default_ledger_path()
    source = source.expanduser()
    destination = (
        Path(dest_dir) if dest_dir is not None else default_backup_dir(source)
    )

    if not source.is_file():
        error = f"observation ledger not found: {source}"
        result = _failure_result(started, created_at=created_at, error=error)
        if record_last_backup:
            recorded, record_error = record_runtime_state(
                source, "last_backup", _runtime_record(result, error=error)
            )
            result["runtime_state_recorded"] = recorded
            result["runtime_state_error"] = record_error
        return result

    temporary: Path | None = None
    final: Path | None = None
    manifest: dict[str, Any] | None = None
    try:
        destination.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        base = f"{BUNDLE_PREFIX}{stamp}"
        sanitized = _sanitize_label(label)
        if sanitized:
            base = f"{base}-{sanitized}"
        name = _unique_bundle_name(destination, base)
        final = destination / name
        temporary = Path(tempfile.mkdtemp(prefix=f".tmp-{name}-", dir=str(destination)))

        ledger_out = temporary / LEDGER_NAME
        _copy_ledger_snapshot(source, ledger_out)
        stats = _ledger_stats(ledger_out)

        raw_info = (
            _copy_raw_cache(source.parent / "cache", temporary / RAW_CACHE_DIR,
                            dest_root=destination)
            if include_raw_cache
            else {
                "included": False,
                "source_dir": _display_path(source.parent / "cache"),
                "files": 0,
                "bytes": 0,
                "note": "raw cache was excluded by request",
            }
        )
        prospective_info = (
            _copy_prospective(temporary / PROSPECTIVE_DIR, dest_root=destination)
            if include_prospective
            else {
                "included": False,
                "source_dir": None,
                "files": 0,
                "bytes": 0,
                "entries": 0,
                "note": "prospective registry was excluded by request",
            }
        )

        (temporary / README_NAME).write_text(
            _render_readme(
                name=name,
                created_at=created_at,
                stats=stats,
                raw_info=raw_info,
                prospective_info=prospective_info,
            ),
            encoding="utf-8",
            newline="\n",
        )

        artifacts = _collect_artifacts(temporary)
        ledger_artifact = next(
            (item for item in artifacts if item["path"] == LEDGER_NAME), None
        )
        ledger_artifact = ledger_artifact or {"bytes": 0, "sha256": None}
        manifest = {
            "schema": BUNDLE_SCHEMA,
            "schema_version": BUNDLE_SCHEMA_VERSION,
            "name": name,
            "created_at": created_at,
            "tool": {
                "name": TOOL_NAME,
                "version": TOOL_VERSION,
                "python": ".".join(str(part) for part in __import__("sys").version_info[:3]),
                "sqlite": sqlite3.sqlite_version,
            },
            "ledger": {
                "schema_version": stats["schema_version"],
                "file": LEDGER_NAME,
                "bytes": ledger_artifact["bytes"],
                "sha256": ledger_artifact["sha256"],
                "integrity_check": stats["integrity_check"],
                "consistency_ok": stats["consistency_ok"],
                "consistency_issue_count": stats["consistency_issue_count"],
                "consistency_issue_counts": stats["consistency_issue_counts"],
            },
            "counts": stats["counts"],
            "first_seen": stats["first_seen"],
            "per_source_observation_counts": stats["per_source_observation_counts"],
            "source_watermarks": stats["source_watermarks"],
            "version_chain": stats["version_chain"],
            "artifacts": artifacts,
            "raw_cache": raw_info,
            "prospective": prospective_info,
            "policy": {
                "ledger_is_system_of_record": True,
                "raw_cache_is_regenerable": True,
                "first_seen_at_is_copied_not_regenerated": True,
                "manifest_not_listed_in_its_own_artifacts": True,
            },
            "notes": [
                "sha256+size cover every artifact except MANIFEST.json itself",
                "the sha256 of MANIFEST.json is recorded in runtime_state['last_backup']",
                "sqlite integrity_check and ledger consistency_check were computed on the copied ledger",
            ],
        }
        _write_json_atomic(temporary / MANIFEST_NAME, manifest)
        _fsync_tree(temporary)

        if final.exists():  # pragma: no cover - guarded by _unique_bundle_name
            raise FileExistsError(f"backup target already exists: {final}")
        os.replace(temporary, final)
        temporary = None  # published; the temp path no longer exists

        verification = verify_backup(final)
        manifest_path = final / MANIFEST_NAME
        manifest_hash = sha256_file(manifest_path) if manifest_path.is_file() else None
        artifacts = manifest.get("artifacts") or []
        total_bytes = sum(int(item.get("bytes") or 0) for item in artifacts)
        ledger_bytes = int((manifest.get("ledger") or {}).get("bytes") or 0)
        verified = bool(verification.get("ok"))

        retention_kept = len(list_backups(destination))
        pruned_now = 0
        if prune_on_create:
            prune_result = prune_backups(destination)
            pruned_now = len(prune_result.get("pruned") or [])
            retention_kept = len(prune_result.get("kept") or [])

        result: dict[str, Any] = {
            "ok": verified,
            "status": "OK" if verified else "UNVERIFIED",
            "verified": verified,
            "bundle": name,
            "path": str(final),
            "ledger": str(final / LEDGER_NAME),
            "bytes": total_bytes,
            "ledger_bytes": ledger_bytes,
            "created_at": created_at,
            "sha256_manifest": manifest_hash,
            "manifest": manifest,
            "verification": verification,
            "counts": manifest.get("counts") or {},
            "first_seen": manifest.get("first_seen") or {},
            "cache_included": bool(raw_info.get("included")),
            "prospective_included": bool(prospective_info.get("included")),
            "retention": {"kept": retention_kept, "pruned": pruned_now},
            "runtime_state_recorded": False,
            "runtime_state_error": None,
            "duration_ms": int((time.monotonic() - started) * 1000),
            "error": None if verified else "; ".join(verification.get("problems") or []),
        }
        if record_last_backup:
            recorded, record_error = record_runtime_state(
                source, "last_backup", _runtime_record(result, error=result["error"])
            )
            result["runtime_state_recorded"] = recorded
            result["runtime_state_error"] = record_error
        return result
    except Exception as exc:  # noqa: BLE001 - operational failure is reported, not raised
        if temporary is not None:
            shutil.rmtree(temporary, ignore_errors=True)
        if final is not None and final.exists():
            # Never leave an unpublished/unverified bundle that looks valid.
            try:
                shutil.rmtree(final)
            except OSError:  # pragma: no cover
                pass
        error = f"{type(exc).__name__}: {exc}"
        result = _failure_result(started, created_at=created_at, error=error)
        if record_last_backup:
            recorded, record_error = record_runtime_state(
                source, "last_backup", _runtime_record(result, error=error)
            )
            result["runtime_state_recorded"] = recorded
            result["runtime_state_error"] = record_error
        return result


def _runtime_record(result: Mapping[str, Any], *, error: str | None) -> dict[str, Any]:
    """The design §2 ``runtime_state["last_backup"]`` structure."""
    counts = result.get("counts") or {}
    return {
        "at": utc_now_iso(),
        "status": "OK" if result.get("ok") else "FAILED",
        "bundle": result.get("bundle"),
        "path": result.get("path"),
        "bytes": int(result.get("bytes") or 0),
        "sha256_manifest": result.get("sha256_manifest"),
        "verified": bool(result.get("verified")),
        "integrity_check": (
            (result.get("manifest") or {}).get("ledger", {}).get("integrity_check")
            if isinstance(result.get("manifest"), Mapping)
            else None
        ),
        "consistency_ok": (
            (result.get("manifest") or {}).get("ledger", {}).get("consistency_ok")
            if isinstance(result.get("manifest"), Mapping)
            else None
        ),
        "counts": {
            "observations": counts.get("observations"),
            "versions": counts.get("versions"),
            "changes": counts.get("changes"),
            "runs": counts.get("runs"),
        },
        "cache_included": bool(result.get("cache_included")),
        "retention": dict(result.get("retention") or {"kept": 0, "pruned": 0}),
        "duration_ms": int(result.get("duration_ms") or 0),
        "error": error,
    }


