def _read_bundle(bundle: Path) -> dict[str, Any]:
    """Cheap structural read used by listing/pruning (no full hash verification)."""
    manifest_path = bundle / MANIFEST_NAME
    info: dict[str, Any] = {"manifest": None, "manifest_status": "MISSING", "error": None}
    if not manifest_path.is_file():
        info["error"] = "MANIFEST.json is missing"
        return info
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        info["manifest_status"] = "CORRUPT"
        info["error"] = f"MANIFEST.json is not valid JSON: {exc}"
        return info
    if not isinstance(manifest, dict):
        info["manifest_status"] = "CORRUPT"
        info["error"] = "MANIFEST.json is not a JSON object"
        return info
    info["manifest"] = manifest
    if not (bundle / LEDGER_NAME).is_file():
        info["manifest_status"] = "INCOMPLETE"
        info["error"] = f"{LEDGER_NAME} is missing"
        return info
    artifacts = manifest.get("artifacts")
    if not isinstance(artifacts, list):
        info["manifest_status"] = "CORRUPT"
        info["error"] = "manifest has no artifact list"
        return info
    missing: list[str] = []
    for entry in artifacts:
        if not isinstance(entry, Mapping) or not isinstance(entry.get("path"), str):
            info["manifest_status"] = "CORRUPT"
            info["error"] = "invalid artifact entry"
            return info
        if not (bundle / entry["path"]).is_file():
            missing.append(entry["path"])
    if missing:
        info["manifest_status"] = "INCOMPLETE"
        info["error"] = "missing artifact(s): " + ", ".join(missing[:5])
        return info
    info["manifest_status"] = "OK"
    return info


def list_backups(dest_dir: str | Path) -> list[dict[str, Any]]:
    """List backup bundles newest-first (no hash verification, structural only)."""
    destination = Path(dest_dir)
    if not destination.is_dir():
        return []
    entries: list[dict[str, Any]] = []
    for child in sorted(destination.iterdir()):
        if not child.is_dir() or not BUNDLE_RE.match(child.name):
            continue
        info = _read_bundle(child)
        manifest = info["manifest"] if isinstance(info.get("manifest"), Mapping) else {}
        moment = _parse_moment(manifest.get("created_at")) if manifest else None
        if moment is None:
            moment = _bundle_moment(child.name)
        files = _tree_files(child)
        entries.append(
            {
                "name": child.name,
                "path": str(child),
                "created_at": _iso(moment) if moment is not None else None,
                "manifest_status": info["manifest_status"],
                "manifest_error": info.get("error"),
                "manifest": info.get("manifest"),
                "files": len(files),
                "bytes": sum(path.stat().st_size for path in files),
            }
        )
    entries.sort(
        key=lambda item: (item.get("created_at") or "", item["name"]), reverse=True
    )
    return entries


def _quarantine_bundle(destination: Path, bundle: Path) -> Path:
    quarantine = destination / QUARANTINE_DIR
    quarantine.mkdir(parents=True, exist_ok=True)
    target = quarantine / bundle.name
    counter = 2
    while target.exists():
        target = quarantine / f"{bundle.name}.{counter}"
        counter += 1
    os.replace(bundle, target)
    return target


def prune_backups(
    dest_dir: str | Path,
    daily: int = 7,
    weekly: int = 4,
    monthly: int = 6,
    dry_run: bool = False,
) -> dict[str, Any]:
    """Apply retention labels; quarantine (never delete) unverifiable bundles.

    Retention labels: keep the newest bundle of each of the ``daily`` most recent
    calendar days, the newest bundle of each of the ``weekly`` most recent ISO
    weeks and the newest bundle of each of the ``monthly`` most recent months.
    The newest bundle overall is never removed.
    """
    destination = Path(dest_dir)
    policy = {
        "daily": max(0, int(daily)),
        "weekly": max(0, int(weekly)),
        "monthly": max(0, int(monthly)),
    }
    result: dict[str, Any] = {
        "dest": str(destination),
        "policy": policy,
        "dry_run": bool(dry_run),
        "ok": False,
        "checked": 0,
        "newest": None,
        "kept": [],
        "pruned": [],
        "pruned_bytes": 0,
        "quarantined": [],
        "problems": [],
        "warnings": [],
    }
    if not destination.is_dir():
        result["problems"].append(f"backup directory not found: {destination}")
        return result
    entries = list_backups(destination)
    result["checked"] = len(entries)
    if not entries:
        result["ok"] = True
        return result

    newest = entries[0]
    result["newest"] = newest["name"]
    kept_names: set[str] = {newest["name"]}
    valid = [entry for entry in entries if entry["manifest_status"] == "OK"]
    # Never prune the newest *verifiable* bundle either: if the chronologically
    # newest bundle is corrupt, the previous good one is still the best copy.
    if valid:
        kept_names.add(valid[0]["name"])
    if newest["manifest_status"] != "OK":
        result["warnings"].append(
            f"the newest bundle {newest['name']} is "
            f"{newest['manifest_status']}: left in place (never deleted), inspect it manually"
        )

    def keep_top(group_key, limit: int) -> None:
        seen: list[Any] = []
        groups: dict[Any, list[dict[str, Any]]] = {}
        for entry in valid:
            moment = _parse_moment(entry.get("created_at"))
            if moment is None:
                kept_names.add(entry["name"])  # never prune what cannot be dated
                continue
            key = group_key(moment)
            if key not in groups:
                groups[key] = []
                seen.append(key)
            groups[key].append(entry)
        for key in seen[: max(0, int(limit))]:
            kept_names.add(groups[key][0]["name"])

    keep_top(lambda moment: moment.date().isoformat(), policy["daily"])
    keep_top(lambda moment: tuple(moment.isocalendar()[:2]), policy["weekly"])
    keep_top(lambda moment: (moment.year, moment.month), policy["monthly"])

    errors: list[str] = []
    destination_resolved = destination.resolve()
    for entry in entries:
        name = entry["name"]
        bundle = destination / name
        if name == newest["name"]:
            result["kept"].append(name)
            continue
        try:
            if bundle.resolve().parent != destination_resolved:
                errors.append(f"refusing to touch a path outside the backup directory: {name}")
                continue
        except OSError:
            errors.append(f"could not resolve bundle path: {name}")
            continue
        if entry["manifest_status"] != "OK":
            reason = entry["manifest_status"] + (
                f": {entry['manifest_error']}" if entry.get("manifest_error") else ""
            )
            if dry_run:
                result["quarantined"].append(
                    {"name": name, "reason": reason, "dry_run": True}
                )
                continue
            try:
                target = _quarantine_bundle(destination, bundle)
            except OSError as exc:
                errors.append(f"could not quarantine {name}: {exc}")
                continue
            result["quarantined"].append(
                {"name": name, "to": str(target), "reason": reason, "dry_run": False}
            )
            continue
        if name in kept_names:
            result["kept"].append(name)
            continue
        size = entry.get("bytes") or 0
        if dry_run:
            result["pruned"].append(name)
            result["pruned_bytes"] += int(size)
            continue
        try:
            shutil.rmtree(bundle)
        except OSError as exc:
            errors.append(f"could not prune {name}: {exc}")
            continue
        result["pruned"].append(name)
        result["pruned_bytes"] += int(size)

    result["problems"] = errors
    result["ok"] = not errors
    return result


