def _compare_counts(
    manifest: Mapping[str, Any], actual: Mapping[str, Any], problems: list[str]
) -> None:
    expected = manifest.get("counts")
    if not isinstance(expected, Mapping):
        problems.append("manifest has no counts object")
        return
    for key in _COUNT_KEYS:
        if key not in expected:
            continue
        if int(expected[key] or 0) != int(actual.get(key) or 0):
            problems.append(
                f"count mismatch for {key}: manifest={expected[key]} ledger={actual.get(key)}"
            )


def _compare_first_seen(
    manifest: Mapping[str, Any],
    actual: Mapping[str, Any],
    problems: list[str],
) -> None:
    expected = manifest.get("first_seen") or {}
    for key in ("min", "max"):
        if expected.get(key) != actual.get(key):
            problems.append(
                f"first_seen.{key} mismatch: manifest={expected.get(key)!r} "
                f"ledger={actual.get(key)!r}"
            )


def _compare_watermarks(
    manifest: Mapping[str, Any],
    actual: Mapping[str, Any],
    problems: list[str],
) -> None:
    expected = manifest.get("source_watermarks") or {}
    if not isinstance(expected, Mapping):
        problems.append("manifest source_watermarks is not an object")
        return
    if dict(expected) != dict(actual):
        for source in sorted(set(expected) | set(actual)):
            if expected.get(source) != actual.get(source):
                problems.append(f"source watermark mismatch for {source}")


def _compare_per_source(
    manifest: Mapping[str, Any],
    actual: Mapping[str, Any],
    problems: list[str],
) -> None:
    expected = manifest.get("per_source_observation_counts") or {}
    if not isinstance(expected, Mapping):
        problems.append("manifest per_source_observation_counts is not an object")
        return
    if {str(k): int(v) for k, v in expected.items()} != {
        str(k): int(v) for k, v in actual.items()
    }:
        problems.append(
            f"per-source observation counts mismatch: manifest={dict(expected)} "
            f"ledger={dict(actual)}"
        )


def _compare_version_chain(
    manifest: Mapping[str, Any],
    actual: Mapping[str, Any],
    problems: list[str],
) -> None:
    expected = manifest.get("version_chain") or {}
    if not isinstance(expected, Mapping):
        problems.append("manifest version_chain is not an object")
        return
    for key, value in expected.items():
        if int(value or 0) != int(actual.get(key) or 0):
            problems.append(
                f"version_chain.{key} mismatch: manifest={value} ledger={actual.get(key)}"
            )


def verify_backup(bundle_path: str | Path) -> dict[str, Any]:
    """Re-hash and re-check a bundle.  ``ok`` is True only on full verification."""
    bundle = Path(bundle_path)
    checked_at = utc_now_iso()
    base: dict[str, Any] = {
        "bundle": str(bundle),
        "checked_at": checked_at,
        "ok": False,
        "status": "UNVERIFIED",
        "problems": [],
        "manifest": None,
        "counts": None,
        "first_seen": None,
    }
    if not bundle.is_dir():
        base["problems"].append(f"backup bundle not found: {bundle}")
        return base
    manifest_path = bundle / MANIFEST_NAME
    if not manifest_path.is_file():
        base["problems"].append(f"MANIFEST.json is missing in {bundle}")
        return base
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        base["problems"].append(f"MANIFEST.json is not valid JSON: {exc}")
        return base
    if not isinstance(manifest, dict):
        base["problems"].append("MANIFEST.json is not a JSON object")
        return base
    base["manifest"] = manifest
    problems: list[str] = []

    # 1) every listed artifact must exist with the recorded size and sha256.
    artifacts = manifest.get("artifacts")
    if not isinstance(artifacts, list) or not artifacts:
        problems.append("manifest has no artifact list")
        artifacts = []
    listed: dict[str, Mapping[str, Any]] = {}
    for entry in artifacts:
        if not isinstance(entry, Mapping) or not isinstance(entry.get("path"), str):
            problems.append(f"invalid artifact entry: {entry!r}")
            continue
        listed[entry["path"]] = entry
    actual_files: dict[str, Path] = {}
    for path in _tree_files(bundle):
        relative = path.relative_to(bundle).as_posix()
        if relative == MANIFEST_NAME:
            continue
        actual_files[relative] = path
    for relative, entry in sorted(listed.items()):
        if Path(relative).is_absolute() or ".." in Path(relative).parts:
            problems.append(f"unsafe artifact path in manifest: {relative!r}")
            continue
        path = bundle / relative
        if not path.is_file():
            problems.append(f"artifact missing: {relative}")
            continue
        actual_size = path.stat().st_size
        expected_size = entry.get("bytes")
        if expected_size is not None and int(expected_size) != actual_size:
            problems.append(
                f"size mismatch for {relative}: manifest={expected_size} actual={actual_size}"
            )
        actual_hash = sha256_file(path)
        if entry.get("sha256") != actual_hash:
            problems.append(
                f"sha256 mismatch for {relative}: manifest={entry.get('sha256')} "
                f"actual={actual_hash}"
            )
    for relative in sorted(set(actual_files) - set(listed)):
        problems.append(f"unmanifested artifact: {relative}")

    # 2) the copied ledger must be structurally valid and match the manifest.
    ledger_path = bundle / LEDGER_NAME
    counts = None
    first_seen = None
    if not ledger_path.is_file():
        problems.append(f"{LEDGER_NAME} is missing from the bundle")
    else:
        integrity = _integrity_check(ledger_path)
        recorded_integrity = (manifest.get("ledger") or {}).get("integrity_check")
        if integrity != "ok":
            problems.append(f"sqlite integrity_check failed: {integrity}")
        elif recorded_integrity not in (None, "ok"):
            problems.append(
                f"manifest records a failed integrity_check: {recorded_integrity}"
            )
        try:
            ledger = ObservationLedger(ledger_path, read_only=True)
        except (sqlite3.Error, OSError) as exc:
            problems.append(f"could not open the copied ledger: {exc}")
        else:
            try:
                counts = ledger.counts()
                _compare_counts(manifest, counts, problems)
                row = ledger.con.execute(
                    "SELECT MIN(first_seen_at) AS minimum, MAX(first_seen_at) AS maximum"
                    " FROM observation"
                ).fetchone()
                first_seen = {
                    "min": row["minimum"] if row else None,
                    "max": row["maximum"] if row else None,
                }
                _compare_first_seen(manifest, first_seen, problems)
                per_source = {
                    str(item["source"]): int(item["n"])
                    for item in ledger.con.execute(
                        "SELECT source, COUNT(*) AS n FROM observation"
                        " GROUP BY source ORDER BY source"
                    ).fetchall()
                }
                _compare_per_source(manifest, per_source, problems)
                watermarks: dict[str, Any] = {}
                for item in ledger.con.execute(
                    "SELECT source, status, last_attempt_at, last_success_at, watermark,"
                    " watermark_updated_at, adapter_version FROM source_state ORDER BY source"
                ).fetchall():
                    watermarks[str(item["source"])] = {
                        "status": item["status"],
                        "last_attempt_at": item["last_attempt_at"],
                        "last_success_at": item["last_success_at"],
                        "watermark": item["watermark"],
                        "watermark_updated_at": item["watermark_updated_at"],
                        "adapter_version": item["adapter_version"],
                    }
                _compare_watermarks(manifest, watermarks, problems)
                chain_row = ledger.con.execute(
                    "SELECT COALESCE(MAX(version_count), 0) AS maximum,"
                    " COALESCE(SUM(CASE WHEN version_count > 1 THEN 1 ELSE 0 END), 0) AS multi,"
                    " COALESCE(SUM(CASE WHEN version_count > 0 THEN 1 ELSE 0 END), 0) AS with_versions"
                    " FROM observation"
                ).fetchone()
                chain = {
                    "max_version_count": int(chain_row["maximum"] or 0),
                    "multi_version_observations": int(chain_row["multi"] or 0),
                    "observations_with_versions": int(chain_row["with_versions"] or 0),
                }
                _compare_version_chain(manifest, chain, problems)
                recorded_schema = (manifest.get("ledger") or {}).get("schema_version")
                if recorded_schema is not None and recorded_schema != counts.get(
                    "schema_version"
                ):
                    problems.append(
                        f"schema_version mismatch: manifest={recorded_schema} "
                        f"ledger={counts.get('schema_version')}"
                    )
                consistency = ledger.consistency_check()
                if not consistency["ok"]:
                    problems.append(
                        "ledger consistency_check failed: "
                        + ", ".join(sorted(consistency["issues"]))
                    )
                recorded_consistency = (manifest.get("ledger") or {}).get(
                    "consistency_ok"
                )
                if recorded_consistency is False and consistency["ok"]:
                    problems.append(
                        "manifest records consistency_ok=false but the copied ledger is clean"
                    )
            finally:
                ledger.close()

    base["problems"] = problems
    base["ok"] = not problems
    base["counts"] = counts
    base["first_seen"] = first_seen
    if base["ok"]:
        base["status"] = "OK"
    elif ledger_path.is_file() and manifest_path.is_file() and counts is not None:
        base["status"] = "FAILED"
    else:
        base["status"] = "UNVERIFIED"
    return base


