def _ledger_cache_evidence(ledger: ObservationLedger) -> dict[str, dict[str, Any]]:
    """Cache keys whose canonical payload is already stored in the ledger."""
    evidence: dict[str, dict[str, Any]] = {}
    rows = ledger.con.execute(
        "SELECT o.observation_id, o.original_url, o.source,"
        " (SELECT COUNT(*) FROM observation_version v WHERE v.observation_id=o.observation_id)"
        "   AS versions"
        " FROM observation o WHERE o.original_url IS NOT NULL AND o.original_url != ''"
    ).fetchall()
    for row in rows:
        if int(row["versions"] or 0) <= 0:
            continue
        key = cache_key_for_url(row["original_url"])
        item = evidence.setdefault(
            key, {"urls": set(), "observation_ids": set(), "sources": set()}
        )
        item["urls"].add(row["original_url"])
        item["observation_ids"].add(row["observation_id"])
        item["sources"].add(row["source"])
    change_rows = ledger.con.execute(
        "SELECT c.url, c.observation_id, c.source,"
        " (SELECT COUNT(*) FROM observation_version v WHERE v.observation_id=c.observation_id)"
        "   AS versions"
        " FROM observation_change c WHERE c.url IS NOT NULL AND c.url != ''"
    ).fetchall()
    for row in change_rows:
        if int(row["versions"] or 0) <= 0:
            continue
        key = cache_key_for_url(row["url"])
        item = evidence.setdefault(
            key, {"urls": set(), "observation_ids": set(), "sources": set()}
        )
        item["urls"].add(row["url"])
        item["observation_ids"].add(row["observation_id"])
        item["sources"].add(row["source"])
    return {
        key: {
            "urls": sorted(value["urls"]),
            "observation_ids": sorted(value["observation_ids"]),
            "sources": sorted(value["sources"]),
        }
        for key, value in evidence.items()
    }


def prune_raw_cache(
    cache_dir: str | Path,
    ledger: ObservationLedger | str | Path | None = None,
    retention_days: int = 180,
    dry_run: bool = False,
) -> dict[str, Any]:
    """Delete only old cache files whose canonical payload the ledger already has.

    Never touches ``*.sqlite``, manifests, prospective registry files or backup
    bundles.  Unconfirmed cache files (no ledger evidence for their URL) are
    retained: the cache may be regenerable, but deleting evidence we cannot prove
    is duplicated is not worth the risk.
    """
    cache = Path(cache_dir)
    result: dict[str, Any] = {
        "cache_dir": str(cache),
        "retention_days": int(retention_days),
        "dry_run": bool(dry_run),
        "ok": False,
        "deleted": [],
        "deleted_count": 0,
        "deleted_bytes": 0,
        "protected": [],
        "skipped_recent": [],
        "skipped_unconfirmed": [],
        "problems": [],
    }
    if not cache.is_dir():
        result["problems"].append(f"raw cache directory not found: {cache}")
        return result
    owns_ledger = False
    ledger_obj: ObservationLedger | None
    if isinstance(ledger, ObservationLedger):
        ledger_obj = ledger
    else:
        try:
            ledger_obj = ObservationLedger(
                ledger if ledger is not None else None, read_only=True
            )
            owns_ledger = True
        except (FileNotFoundError, sqlite3.Error) as exc:
            result["problems"].append(f"could not open the observation ledger: {exc}")
            return result
    try:
        evidence = _ledger_cache_evidence(ledger_obj)
        result["ledger_counts"] = ledger_obj.counts()
    finally:
        if owns_ledger and ledger_obj is not None:
            ledger_obj.close()

    cutoff = time.time() - max(0, int(retention_days)) * 86400.0
    for path in sorted(cache.iterdir(), key=lambda item: item.name):
        if path.is_dir():
            result["protected"].append(path.name)
            continue
        name = path.name
        if not CACHE_FILE_RE.match(name):
            result["protected"].append(name)
            continue
        try:
            stat = path.stat()
        except OSError as exc:
            result["problems"].append(f"could not stat {name}: {exc}")
            continue
        if stat.st_mtime > cutoff:
            result["skipped_recent"].append(name)
            continue
        key = name.split(".", 1)[0]
        if key not in evidence:
            result["skipped_unconfirmed"].append(name)
            continue
        if dry_run:
            result["deleted"].append(name)
            result["deleted_bytes"] += stat.st_size
            continue
        try:
            path.unlink()
        except OSError as exc:
            result["problems"].append(f"could not delete {name}: {exc}")
            continue
        result["deleted"].append(name)
        result["deleted_bytes"] += stat.st_size

    result["deleted_count"] = len(result["deleted"])
    result["ok"] = not result["problems"]
    return result


