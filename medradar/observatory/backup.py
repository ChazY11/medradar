#: ``observatory-YYYYMMDDTHHMMSSZ`` with an optional human label suffix.
BUNDLE_RE = re.compile(r"^observatory-(?P<stamp>\d{8}T\d{6}Z)(?:-(?P<label>.+))?$")
#: Raw HTTP cache file names produced by ``medradar.http.Fetcher._key`` (sha1[:24]).
CACHE_FILE_RE = re.compile(r"^[0-9a-f]{24}\.(?:json|txt)$")

#: Counts copied into the manifest and compared on verification.
_COUNT_KEYS = (
    "observations",
    "versions",
    "changes",
    "runs",
    "failures",
    "sources",
    "live_observations",
    "backfilled_observations",
    "removed_observations",
)

_CHUNK = 1024 * 1024


# ----------------------------------------------------------------------- helpers
def sha256_file(path: str | Path) -> str:
    """SHA-256 of one file, read in bounded chunks."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            block = handle.read(_CHUNK)
            if not block:
                break
            digest.update(block)
    return digest.hexdigest()


def cache_key_for_url(url: str) -> str:
    """The cache file key ``medradar.http.Fetcher`` would use for ``url``."""
    return hashlib.sha1(str(url).encode("utf-8")).hexdigest()[:24]


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _parse_moment(value: Any) -> datetime | None:
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    try:
        moment = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return None
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return moment.astimezone(timezone.utc)


def _iso(moment: datetime) -> str:
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _display_path(path: str | Path) -> str:
    """Relative path inside the checkout when possible, else the absolute path."""
    target = Path(path)
    try:
        return target.resolve().relative_to(Path.cwd().resolve()).as_posix()
    except (OSError, ValueError):
        return str(target)


def _is_relative_to(path: Path, parent: Path) -> bool:
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except (OSError, ValueError):
        return False


def _fsync_file(path: str | Path) -> None:
    try:
        with open(path, "rb") as handle:
            os.fsync(handle.fileno())
    except OSError:  # pragma: no cover - best effort on exotic filesystems
        pass


def _fsync_tree(root: Path) -> None:
    """Best-effort fsync of every file and directory under ``root``."""
    directories = [root]
    for path in root.rglob("*"):
        if path.is_dir():
            directories.append(path)
        else:
            _fsync_file(path)
    for directory in reversed(directories):
        try:
            descriptor = os.open(str(directory), os.O_RDONLY)
        except OSError:  # Windows cannot open directories; durability is best-effort
            continue
        try:
            os.fsync(descriptor)
        except OSError:  # pragma: no cover
            pass
        finally:
            os.close(descriptor)


def _atomic_write_bytes(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f"{path.name}.tmp-{os.getpid()}-{os.urandom(3).hex()}")
    with open(temporary, "wb") as handle:
        handle.write(data)
        handle.flush()
        try:
            os.fsync(handle.fileno())
        except OSError:  # pragma: no cover
            pass
    os.replace(temporary, path)


def _atomic_copy_file(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(
        f"{destination.name}.tmp-{os.getpid()}-{os.urandom(3).hex()}"
    )
    shutil.copy2(source, temporary)
    _fsync_file(temporary)
    os.replace(temporary, destination)


def _tree_files(root: Path) -> list[Path]:
    if not root.is_dir():
        return []
    return sorted(path for path in root.rglob("*") if path.is_file())


def _tree_size(root: Path) -> int:
    return sum(path.stat().st_size for path in _tree_files(root) if path.exists())


def _write_json_atomic(path: Path, payload: Mapping[str, Any]) -> None:
    text = json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    _atomic_write_bytes(path, text.encode("utf-8"))


# ------------------------------------------------------------------- paths / names
def default_backup_dir(ledger_path: str | Path | None = None) -> Path:
    """Default local staged-backup directory: ``<ledger dir>/backups``.

    Co-locating the bundles with the ledger is what lets ``health``/``audit``
    discover the newest bundle (``<ledger dir>/backups/observatory-*``) without
    configuration.  Pass an explicit ``dest_dir`` to stage backups on another
    volume (e.g. a dedicated backup disk) instead.
    """
    if ledger_path is not None:
        return Path(ledger_path).expanduser().parent / "backups"
    return default_ledger_path().parent / "backups"


def _sanitize_label(label: Any) -> str | None:
    if label is None:
        return None
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "-", str(label).strip()).strip("-._")
    return cleaned[:48] or "backup"


def _unique_bundle_name(destination: Path, base: str) -> str:
    candidate = base
    counter = 2
    while (destination / candidate).exists():
        candidate = f"{base}-{counter}"
        counter += 1
    return candidate


def _bundle_moment(name: str) -> datetime | None:
    match = BUNDLE_RE.match(name)
    if not match:
        return None
    try:
        return datetime.strptime(match.group("stamp"), "%Y%m%dT%H%M%SZ").replace(
            tzinfo=timezone.utc
        )
    except ValueError:  # pragma: no cover - regex already constrains the shape
        return None


# ------------------------------------------------------------------- ledger stats
def _integrity_check(path: Path) -> str:
    """Run ``PRAGMA integrity_check`` read-only; return the raw result string."""
    uri = f"file:{path.as_posix()}?mode=ro"
    try:
        connection = sqlite3.connect(uri, uri=True, timeout=45.0, isolation_level=None)
    except sqlite3.Error as exc:  # pragma: no cover - unreadable file
        return f"error: {exc}"
    try:
        connection.execute("PRAGMA query_only=ON")
        row = connection.execute("PRAGMA integrity_check").fetchone()
        return str(row[0]) if row else "error: empty integrity_check result"
    except sqlite3.DatabaseError as exc:
        return f"error: {exc}"
    finally:
        connection.close()


def _ledger_stats(path: Path) -> dict[str, Any]:
    """Describe the *copied* ledger so the manifest describes the artifact itself."""
    ledger = ObservationLedger(path, read_only=True)
    try:
        counts = ledger.counts()
        first_seen_row = ledger.con.execute(
            "SELECT MIN(first_seen_at) AS minimum, MAX(first_seen_at) AS maximum FROM observation"
        ).fetchone()
        per_source = {
            str(row["source"]): int(row["n"])
            for row in ledger.con.execute(
                "SELECT source, COUNT(*) AS n FROM observation GROUP BY source ORDER BY source"
            ).fetchall()
        }
        watermarks: dict[str, Any] = {}
        for row in ledger.con.execute(
            "SELECT source, status, last_attempt_at, last_success_at, watermark,"
            " watermark_updated_at, adapter_version FROM source_state ORDER BY source"
        ).fetchall():
            watermarks[str(row["source"])] = {
                "status": row["status"],
                "last_attempt_at": row["last_attempt_at"],
                "last_success_at": row["last_success_at"],
                "watermark": row["watermark"],
                "watermark_updated_at": row["watermark_updated_at"],
                "adapter_version": row["adapter_version"],
            }
        chain = ledger.con.execute(
            "SELECT COALESCE(MAX(version_count), 0) AS maximum,"
            " COALESCE(SUM(CASE WHEN version_count > 1 THEN 1 ELSE 0 END), 0) AS multi,"
            " COALESCE(SUM(CASE WHEN version_count > 0 THEN 1 ELSE 0 END), 0) AS with_versions"
            " FROM observation"
        ).fetchone()
        consistency = ledger.consistency_check()
    finally:
        ledger.close()
    integrity = _integrity_check(path)
    schema_version = counts.get("schema_version")
    return {
        "counts": {key: counts.get(key) for key in _COUNT_KEYS},
        "ledger_counts": counts,
        "first_seen": {
            "min": first_seen_row["minimum"] if first_seen_row else None,
            "max": first_seen_row["maximum"] if first_seen_row else None,
        },
        "per_source_observation_counts": per_source,
        "source_watermarks": watermarks,
        "version_chain": {
            "max_version_count": int(chain["maximum"] or 0),
            "multi_version_observations": int(chain["multi"] or 0),
            "observations_with_versions": int(chain["with_versions"] or 0),
        },
        "schema_version": schema_version,
        "integrity_check": integrity,
        "consistency_ok": bool(consistency["ok"]),
        "consistency_issue_count": int(consistency["issue_count"]),
        "consistency_issue_counts": {
            name: len(rows) for name, rows in sorted(consistency["issues"].items())
        },
    }


def _copy_ledger_snapshot(source: Path, destination: Path) -> None:
    """Consistent copy through the SQLite online backup API (WAL-safe)."""
    uri = f"file:{source.as_posix()}?mode=ro"
    try:
        source_connection = sqlite3.connect(
            uri, uri=True, timeout=45.0, isolation_level=None
        )
        source_connection.execute("PRAGMA query_only=ON")
    except sqlite3.Error:
        # Fall back to a plain connection: the backup API still produces a
        # consistent snapshot, but a read-only handle is preferred.
        source_connection = sqlite3.connect(
            str(source), timeout=45.0, isolation_level=None
        )
    destination.parent.mkdir(parents=True, exist_ok=True)
    try:
        destination_connection = sqlite3.connect(
            str(destination), timeout=45.0, isolation_level=None
        )
        try:
            source_connection.backup(destination_connection)
            # The backup destination may inherit the WAL header from the source;
            # switch it back to a single-file rollback journal so the bundle is
            # self-contained and readable without -wal/-shm sidecars.
            destination_connection.execute("PRAGMA journal_mode=DELETE")
        finally:
            destination_connection.close()
    finally:
        source_connection.close()
    for suffix in ("-wal", "-shm"):
        sidecar = Path(str(destination) + suffix)
        if sidecar.exists():
            try:
                sidecar.unlink()
            except OSError:  # pragma: no cover
                pass
    _fsync_file(destination)


def _copy_raw_cache(source: Path, destination: Path, *, dest_root: Path) -> dict[str, Any]:
    """Copy the raw HTTP response cache (regenerable evidence) read-only."""
    info: dict[str, Any] = {
        "included": False,
        "source_dir": _display_path(source),
        "files": 0,
        "bytes": 0,
        "note": "raw HTTP responses are regenerable evidence, not the system of record",
    }
    if not source.is_dir():
        info["note"] = "raw cache directory does not exist; nothing to copy"
        return info
    if _is_relative_to(dest_root, source):
        info["note"] = "skipped: backup destination is inside the raw cache directory"
        return info
    shutil.copytree(source, destination, dirs_exist_ok=True)
    files = _tree_files(destination)
    info.update(
        {
            "included": True,
            "files": len(files),
            "bytes": sum(path.stat().st_size for path in files),
            "note": "full read-only copy of the raw response cache",
        }
    )
    return info


def _copy_prospective(destination: Path, *, dest_root: Path) -> dict[str, Any]:
    """Copy the frozen prospective registry read-only (if it exists)."""
    from .prospective import default_registry_dir

    registry = default_registry_dir()
    info: dict[str, Any] = {
        "included": False,
        "source_dir": _display_path(registry),
        "files": 0,
        "bytes": 0,
        "entries": 0,
        "note": "frozen prospective registry documents are copied read-only",
    }
    if not registry.is_dir():
        info["note"] = "prospective registry does not exist; nothing to copy"
        return info
    if _is_relative_to(dest_root, registry):
        info["note"] = "skipped: backup destination is inside the prospective registry"
        return info
    shutil.copytree(registry, destination, dirs_exist_ok=True)
    files = _tree_files(destination)
    entries_dir = destination / "entries"
    frozen_entries = 0
    if entries_dir.is_dir():
        # Frozen core documents only; evaluation/status appendices are counted
        # as files, not as entries (same rule as the registry itself).
        appendix_re = re.compile(r"\.(?:evaluation|status)\.\d+\.json$")
        frozen_entries = len(
            [
                path
                for path in entries_dir.glob("*.json")
                if path.is_file() and not appendix_re.search(path.name)
            ]
        )
    info.update(
        {
            "included": True,
            "files": len(files),
            "bytes": sum(path.stat().st_size for path in files),
            "entries": frozen_entries,
        }
    )
    return info


def _role_for(relative: str) -> str:
    if relative == LEDGER_NAME:
        return "ledger"
    if relative == README_NAME:
        return "doc"
    head = relative.split("/", 1)[0]
    if head == RAW_CACHE_DIR:
        return "raw_cache"
    if head == PROSPECTIVE_DIR:
        return "prospective"
    return "other"


def _collect_artifacts(root: Path) -> list[dict[str, Any]]:
    artifacts: list[dict[str, Any]] = []
    for path in _tree_files(root):
        relative = path.relative_to(root).as_posix()
        if relative == MANIFEST_NAME:
            continue
        artifacts.append(
            {
                "path": relative,
                "role": _role_for(relative),
                "bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
        )
    return artifacts


