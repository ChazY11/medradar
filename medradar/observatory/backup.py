"""Verified backup subsystem for the Observation Ledger.

This module exists because a backup that has never been hash-verified is not a
backup: it is a directory that might restore.  The contract implemented here is
design §2 of ``docs/RELIABILITY_DESIGN.md``:

* a live SQLite database is snapshotted with the **online backup API**
  (``sqlite3.Connection.backup``) — never a raw file copy of a WAL database, so
  a concurrent writer cannot produce a torn snapshot;
* every bundle is built in a temporary directory under the destination and
  published with a single directory rename, so a crash can never leave a
  half-written directory that looks like a valid backup;
* ``MANIFEST.json`` records sha256 + size for every artifact, the ledger counts,
  first_seen min/max, per-source observation counts, source watermarks, the
  SQLite ``integrity_check`` result, the ledger ``consistency_check()`` result,
  the schema version and the tool versions;
* ``verify_backup`` re-hashes every artifact, re-runs ``PRAGMA integrity_check``
  on the copied database and re-compares counts/first_seen against the manifest.
  Until that passes the bundle is reported ``UNVERIFIED``/``FAILED`` — never OK;
* ``prune_backups`` implements retention labels (newest N daily + newest bundle
  per ISO week for N weeks + newest bundle per month for N months).  A bundle
  whose ``MANIFEST.json`` is missing or corrupt is never deleted: it is moved to
  ``<dest>/quarantine/`` and reported;
* ``prune_raw_cache`` may only delete raw HTTP cache files that are older than
  the retention window *and* whose canonical payload is already stored in the
  ledger (the cache is regenerable, the ledger is not);
* the outcome is written to ledger ``runtime_state["last_backup"]`` so the
  health panel can report the truth.

Honesty rules encoded here: no network access, no credentials, no deletion of
the only copy of the ledger, no pruning of anything under ``data/prospective``,
and ``first_seen_at`` is never regenerated by this module.
"""

