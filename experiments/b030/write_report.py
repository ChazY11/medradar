"""Generate experiments/b030/REPORT.md from hiring_panel.json and lag_analysis.json.

Every number is read from the artifacts; none is typed by hand.

    python experiments/b030/write_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

BASE = Path("experiments/b030")


def num(value, digits: int = 3) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "—"


def main() -> int:
    panel = json.loads((BASE / "hiring_panel.json").read_text(encoding="utf-8"))
    lag = json.loads((BASE / "lag_analysis.json").read_text(encoding="utf-8"))
    design = panel["design"]
    coverage = panel["coverage"]
    lag_cov = lag["coverage"]

    lines: list[str] = []
    add = lines.append
    add("# B-030 — a lawful point-in-time hiring signal: obtained, measured, currently too thin")
    add("")
    add("Generated by `write_report.py` from `hiring_panel.json` and `lag_analysis.json`; no number "
        "is typed by hand. Source selection, proxy definition and analyses were pre-registered in "
        "DECISIONS D-028 before any association was computed.")
    add("")
    add("## Why this was attempted")
    add("")
    add("Six cycles established that the regulatory filing lane cannot support the programme's "
        "questions: ~0.2 events per cell-month, no independent confirmation source until B-040, and "
        "every clustering claim dissolved under its own control. The declared next step was a **denser "
        "independent signal** — hiring — collected with genuine historical point-in-time availability.")
    add("")
    add("## Source selection, measured")
    add("")
    add("| candidate route | probe result |")
    add("|---|---|")
    add("| PatentsView bulk (S3) | **403 Forbidden** — credentials required; patents stay blocked |")
    add("| Common Crawl index API | **persistent 504 Gateway Time-out**, even for `example.com` |")
    add("| **Wayback Machine CDX** | **works, keyless**, and archives real job-posting URLs "
        "(Medtronic's `jobs.medtronic.com/job/*` alone has 15 index pages) |")
    add("")
    add("The Wayback route was adopted: public web archive, **index only** (no page content fetched), "
        "bounded pages and rate-limited queries. Its key property for this programme is that the "
        "archive predates the analysis by years, so the signal is genuinely historical rather than "
        "reconstructed by our own collection.")
    add("")
    add(f"## The proxy")
    add("")
    add(f"* {design['proxy']}.")
    add(f"* Window {design['window'][0]}–{design['window'][1]}; ≤{design['max_pages_per_pattern']} "
        f"index pages per pattern; {design['delay_seconds']} s between requests.")
    add("* It is a **posting-flow proxy, not headcount**: it counts postings the archive happened to "
        "capture, so archive coverage, URL-scheme stability and crawl cadence all enter the signal.")
    add("")
    add("## Coverage actually achieved")
    add("")
    add(f"{coverage['companies_tried']} device firms were probed; "
        f"**{coverage['companies_with_postings']} yielded any posting URLs** and "
        f"**{coverage['companies_usable']} cleared the pre-declared usability floor** "
        f"(≥{lag['design']['eligibility']['min_postings']} postings, "
        f"≥{lag['design']['eligibility']['min_months']} months, "
        f"≤{int(lag['design']['eligibility']['max_silent_month_fraction']*100)} % silent months).")
    add("")
    add("| company | postings | months with postings | silent-month fraction | usable |")
    add("|---|---:|---:|---:|---|")
    for company, block in panel["companies"].items():
        detail = lag_cov["usable_detail"].get(company)
        if detail:
            add(f"| {company} | {detail['total']} | {detail['months_with_postings']} | "
                f"{detail['silent_month_fraction']:.2f} | yes |")
        elif block.get("distinct_postings"):
            add(f"| {company} | {block['distinct_postings']} | {block['months_covered']} | — | "
                f"no ({block.get('status')}) |")
        else:
            add(f"| {company} | 0 | 0 | — | no (no archived postings) |")
    add("")
    add(f"**Usable companies: {len(lag_cov['usable_keys'])}** — "
        f"{', '.join(lag_cov['usable_keys']) if lag_cov['usable_keys'] else 'none'}.")
    add("")
    add("## The lag profile, and why it must not be interpreted")
    add("")
    add("| lag (months) | companies | pooled r | null 95 % interval |")
    add("|---:|---:|---:|---|")
    for lag_value in lag["design"]["lags"]:
        block = lag["lag_profile"][str(lag_value)]
        add(f"| {lag_value:+d} | {block['companies']} | {num(block['observed'])} | "
            f"[{num(block['null_low'])}, {num(block['null_high'])}] |")
    add("")
    add("**This table is not a finding.** The pooled profile rests on "
        f"{len(lag_cov['usable_keys'])} companies, one of them at the silence threshold, and its "
        "values are all negative while the archive-driven proxy makes the sign uninterpretable: a "
        "month counts only if the archive captured a posting, so capture gaps and regulatory gaps "
        "can align for reasons that have nothing to do with hiring. With two companies the pooled "
        "correlation is close to an average of two numbers and carries no useful standard error.")
    add("")
    add("## What was achieved, and what is missing")
    add("")
    add("**Achieved.** A lawful, keyless, genuinely historical hiring proxy; a bounded and "
        "rate-limited collector; a committed panel artifact; and a measured coverage map. That is the "
        "first time this programme has a real independent hiring signal in hand rather than a "
        "declared gap.")
    add("")
    add("**Missing, and why it blocks inference:**")
    add("")
    add("* **Domain discovery.** Several focus companies returned nothing because their career sites "
        "live on hosts the patterns did not guess (Philips, GE HealthCare, Dräger, Mindray, Abbott, "
        "Zimmer Biomet, Masimo, Hologic). Fixing this is a per-company domain problem, not a "
        "statistical one.")
    add("* **Archive depth.** Medtronic's index has 15 pages; the collector now pages up to 16, but "
        "capture cadence still varies by year, so a monthly series mixes hiring with crawling.")
    add("* **Platform changes.** Career sites migrate between posting-URL schemes; a migration "
        "creates a level shift that is a collection artifact. This must be detected per company "
        "before any level-shift analysis.")
    add("")
    add("## Verdict")
    add("")
    add("B-030 is a **feasibility partial**: the source exists and is lawful, the pipeline works, and "
        "the coverage is not yet sufficient for the company-level lag question it was built for. The "
        "honest next step is coverage completion (per-company career-domain mapping, platform-change "
        "audit), and only then the pre-registered lag test — which remains unrun rather than run and "
        "misreported.")
    add("")
    add("## Reproduction")
    add("")
    add("```bash")
    add("cd D:\\DEPPSKK\\worktrees\\integration-v2")
    add("$env:PYTHONIOENCODING=\"utf-8\"")
    add("python experiments/b030/hiring_panel.py     # bounded Wayback CDX collection")
    add("python experiments/b030/lag_analysis.py     # coverage + lag profile (NOT a finding)")
    add("python experiments/b030/write_report.py     # this report")
    add("```")
    add("")
    (BASE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {BASE / 'REPORT.md'} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
