"""Generate experiments/b030/REPORT.md from the corrected hiring artifacts.

Reads hiring_panel_v2.json, lag_analysis_v2.json and host_depth.json; every number comes from
those files.

    python experiments/b030/write_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

BASE = Path("experiments/b030")


def num(value, digits: int = 3) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "—"


def main() -> int:
    panel = json.loads((BASE / "hiring_panel_v2.json").read_text(encoding="utf-8"))
    lag = json.loads((BASE / "lag_analysis_v2.json").read_text(encoding="utf-8"))
    depth = json.loads((BASE / "host_depth.json").read_text(encoding="utf-8"))
    design = panel["design"]
    coverage = panel["coverage"]
    lag_cov = lag["coverage"]

    lines: list[str] = []
    add = lines.append
    add("# B-030 / B-047 — a lawful historical hiring lane, and a collector bug that hid most of it")
    add("")
    add("Generated by `write_report.py` from `hiring_panel_v2.json`, `lag_analysis_v2.json` and "
        "`host_depth.json`. No number is typed by hand. Source selection and the lag test were "
        "pre-registered in DECISIONS D-028; the correction below is recorded in D-030.")
    add("")
    add("## 1. The correction first: cycle 9's coverage conclusion was partly my bug")
    add("")
    add("Cycle 9 reported that the Wayback hiring proxy covered only 2 usable companies and blamed "
        "archive depth. That was **wrong**. The collector combined `collapse=urlkey` with `limit` + "
        "`page` pagination; that combination does not page on this endpoint, so every query silently "
        "returned one capped page and most of the archive was invisible.")
    add("")
    add("A direct per-host measurement with a single generous request shows the same hosts hold far "
        "more:")
    add("")
    add("| host | posting URLs | months | months with ≥5 postings |")
    add("|---|---:|---:|---:|")
    for row in depth["hosts"]:
        if row.get("error"):
            add(f"| `{row['pattern']}` | error | — | — |")
        else:
            add(f"| `{row['pattern']}` | {row['posting_urls']} | {row['months']} | "
                f"{row['months_with_5plus']} |")
    add("")
    add(f"Corrected panel coverage: **{coverage['companies_with_postings']} companies with posting "
        f"URLs**, {coverage['companies_with_24plus_months']} with ≥24 months, "
        f"{coverage['companies_with_50plus_postings']} with ≥50 postings — against 2 usable "
        f"companies in cycle 9.")
    add("")
    add("## 2. Source selection (unchanged, measured)")
    add("")
    add("| candidate route | probe result |")
    add("|---|---|")
    add("| PatentsView bulk (S3) | **403 Forbidden** — credentials required; patents stay blocked |")
    add("| Common Crawl index API | **persistent 504**, even for `example.com` |")
    add("| **Wayback Machine CDX** | **works keyless**; archives real job-posting URLs |")
    add("")
    add("The Wayback route is used as index-only access (no page content), rate-limited and bounded. "
        "It remains lawful and genuinely historical: the archive predates the analysis by years.")
    add("")
    add("## 3. Corrected coverage")
    add("")
    add("| company | postings (v2) | months | truncated | status |")
    add("|---|---:|---:|---|---|")
    for company, block in panel["companies"].items():
        if not block.get("distinct_postings"):
            add(f"| {company} | 0 | 0 | — | no coverage |")
        else:
            add(f"| {company} | {block['distinct_postings']} | {block['months']} | "
                f"{block.get('truncated')} | collected |")
    add("")
    add(f"The `limit` is {design['limit']} per host; `truncated` marks hosts where the cap was hit, "
        "so the table understates rather than overstates depth.")
    add("")
    add("Companies still without coverage: "
        + ", ".join(company for company, block in panel["companies"].items()
                    if not block.get("distinct_postings")) + ".")
    add("")
    add("## 4. The lag test on the corrected panel — still not a result")
    add("")
    add("Usable companies under the unchanged pre-declared floor: "
        f"**{len(lag_cov['usable_keys'])}** ({', '.join(lag_cov['usable_keys'])}).")
    add("")
    add("| lag (months) | companies | pooled r | null 95 % interval |")
    add("|---:|---:|---:|---|")
    for lag_value in lag["design"]["lags"]:
        block = lag["lag_profile"][str(lag_value)]
        add(f"| {lag_value:+d} | {block['companies']} | {num(block['observed'])} | "
            f"[{num(block['null_low'])}, {num(block['null_high'])}] |")
    add("")
    add(f"With {len(lag_cov['usable_keys'])} companies the pooled profile has no usable standard "
        "error, and every value sits inside its null band. The uniformly negative sign is **not "
        "interpretable**: the proxy counts only postings the archive happened to capture, so capture "
        "gaps and regulatory gaps can align for reasons unrelated to hiring. This is an **unrun "
        "question with working machinery**, not a null result about hiring.")
    add("")
    add("## 5. What is now established, and what still blocks")
    add("")
    add("**Established.** The hiring lane is lawful, keyless and historical; it now covers "
        f"{coverage['companies_with_24plus_months']} firms with ≥24 months of posting data; the "
        "collector's truncation is recorded per host rather than hidden; and the posting-URL shape "
        "audit is stored for platform-migration detection.")
    add("")
    add("**Still blocking a verdict:**")
    add("")
    add("* **Statistical power.** 3 usable companies cannot support a lag inference at any "
        "correction level. More firms must clear the floor, not a looser floor.")
    add("* **Platform migrations.** `shape_first_seen` is recorded per company; a switch between "
        "posting-URL templates creates a level shift that is a collection artifact and must be "
        "excluded before any level-shift claim.")
    add("* **Missing firms.** Philips, Dräger, Mindray, Zimmer Biomet and Masimo still return no "
        "archived postings under the probed hosts — including two of the five mandated focus "
        "companies.")
    add("* **Truncation.** Medtronic, BD, Boston Scientific and Stryker hit the per-host cap, so "
        "their series are lower bounds.")
    add("")
    add("## 6. Verdict")
    add("")
    add("This report is **not** a science result and does not pretend otherwise. It is the correction "
        "of a measurement bug that had produced a false conclusion (\"coverage too thin\"), plus a "
        "much better coverage map and a pre-registered test that is honestly reported as unrun. The "
        "B-030 lag question needs more *companies*, not a better estimator — and the remaining "
        "blocker is now specific: career-board discovery for five firms, of which two are mandated "
        "focus cases.")
    add("")
    add("## 7. Reproduction")
    add("")
    add("```bash")
    add("cd D:\\DEPPSKK\\worktrees\\integration-v2")
    add("$env:PYTHONIOENCODING=\"utf-8\"")
    add("python experiments/b030/probe_ats_hosts.py        # discover ATS job boards")
    add("python experiments/b030/measure_host_depth.py     # archive depth per host")
    add("python experiments/b030/hiring_panel_v2.py        # corrected panel")
    add("python experiments/b030/lag_analysis.py --panel experiments/b030/hiring_panel_v2.json "
        "--out experiments/b030/lag_analysis_v2.json")
    add("python experiments/b030/write_report.py           # this report")
    add("```")
    add("")
    (BASE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {BASE / 'REPORT.md'} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
