def part1b_deltas(h: dict, boot: dict, summary: dict | None):
    """Exact deltas between this verifier's recomputation and summary.json."""
    if summary is None:
        return {"status": "summary.json not available -> deltas NOT VERIFIED"}
    pc = (summary.get("verdict") or {}).get("primary_contrast") or {}
    rep_ci = pc.get("ci95") or [None, None]
    d = {
        "reported": {k: pc.get(k) for k in ("n", "n_pos", "prevalence", "ap_a", "ap_b",
                                            "dap", "ci95", "n_tracks", "p")},
        "recomputed": {"n": h["n"], "n_pos": h["n_pos"], "prevalence": h["prevalence"],
                       "ap_a": h["ap_M4_h8_growth"], "ap_b": h["ap_M1_persistence"],
                       "dap": h["dap"], "n_tracks": h["n_tracks"],
                       "ci95_bootstrap_seed20261109":
                           boot["per_seed"].get("20261109", {}).get("ci95")},
        "deltas_recomputed_minus_reported": {},
        "verdict_on_agreement": {},
    }
    for k in ("n", "n_pos", "prevalence", "dap", "ap_a", "ap_b"):
        rv = h.get(k) if k in h else h.get("ap_M4_h8_growth" if k == "ap_a" else "ap_M1_persistence")
        if k in ("n", "n_pos"):
            rv = h[k]
        if pc.get(k) is not None and rv is not None:
            d["deltas_recomputed_minus_reported"][k] = float(rv) - float(pc[k])
    # CI agreement: is the reported CI inside the range spanned by our seeds?
    bs = boot["across_seeds"]
    if rep_ci[0] is not None:
        d["ci_agreement"] = {
            "reported_ci95": rep_ci,
            "my_seed_ci_low_range": [bs["ci95_low_min"], bs["ci95_low_max"]],
            "my_seed_ci_high_range": [bs["ci95_high_min"], bs["ci95_high_max"]],
            "reported_low_within_my_range":
                bool(bs["ci95_low_min"] - 2e-3 <= rep_ci[0] <= bs["ci95_low_max"] + 2e-3),
            "reported_high_within_my_range":
                bool(bs["ci95_high_min"] - 2e-3 <= rep_ci[1] <= bs["ci95_high_max"] + 2e-3),
            "tolerance": 0.002,
            "note": "different RNG stream reproduces the same interval up to Monte-Carlo error; "
                    "an exact match is not expected",
        }
    d["verdict_on_agreement"]["headline_numbers_reproduced"] = all(
        abs(v) < 1e-9 for v in d["deltas_recomputed_minus_reported"].values())
    d["verdict_on_agreement"]["max_abs_delta"] = (max(
        (abs(v) for v in d["deltas_recomputed_minus_reported"].values()), default=None))
    log("    deltas:", d["deltas_recomputed_minus_reported"])
    log("    max|delta|:", d["verdict_on_agreement"]["max_abs_delta"])
    return d


def part7_attribution_strata(d_primary: pd.DataFrame, summary: dict | None):
    """A5: recompute the attribution-coverage stratified contrast independently.

    Attribution rate per track is computed by this verifier from the frozen DB:
      rate = (# tracked device events with company_key) / (# tracked device events)
    over the frozen window, then the OOF primary rows are split at 50%.
    """
    log("[part7] A5 attribution-coverage strata (independent)")
    import sqlite3
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    try:
        sql = """
        select track_id,
               sum(case when company_key is not null then 1 else 0 end) as attributed,
               count(*) as tracked
        from events
        where kind in ('510k','pma') and track_id is not null
          and event_date is not null
          and event_date >= '2004-01-01' and event_date <= '2026-10-30'
        group by track_id
        """
        att = pd.read_sql_query(sql, con)
    finally:
        con.close()
    att["attribution_rate"] = att["attributed"] / att["tracked"]
    att = att.rename(columns={"attribution_rate": "my_attribution_rate"})

    have_col = "attribution_rate" in d_primary.columns
    d = d_primary.merge(att[["track_id", "attributed", "tracked", "my_attribution_rate"]],
                        on="track_id", how="left")
    res = {"definition": "track attribution rate = attributed tracked device events / all "
                         "tracked device events (510k+pma, 2004-2026); high >= 0.50",
           "n_tracks_with_data": int(att["track_id"].nunique()),
           "n_oof_rows_missing_rate": int(d["my_attribution_rate"].isna().sum()),
           "rate_median": float(att["my_attribution_rate"].median()),
           "oof_file_carries_attribution_rate_column": have_col,
           "strata": {}}
    if have_col:
        diff = (d["attribution_rate"] - d["my_attribution_rate"]).abs()
        res["crosscheck_vs_oof_column"] = {
            "max_abs_diff": float(diff.max()),
            "n_rows_over_1e_6": int((diff > 1e-6).sum()),
            "agrees": bool(diff.max() < 1e-6),
        }
        log(f"    cross-check of oof attribution_rate vs my DB rate: max|diff|={diff.max():.2e}")
    for name, mask in (("high_attribution_ge_50pct", d["my_attribution_rate"] >= 0.50),
                       ("low_attribution_lt_50pct", d["my_attribution_rate"] < 0.50)):
        sub = d[mask]
        if len(sub) == 0 or sub["y"].sum() == 0:
            res["strata"][name] = {"n": int(len(sub)), "n_pos": int(sub["y"].sum()),
                                   "dap": None, "note": "not evaluable"}
            continue
        a1 = float(average_precision_score(sub["y"], sub["M4_h8_growth"]))
        a0 = float(average_precision_score(sub["y"], sub["M1_persistence"]))
        res["strata"][name] = {
            "n": int(len(sub)), "n_pos": int(sub["y"].sum()),
            "n_tracks": int(sub["track_id"].nunique()),
            "prevalence": float(sub["y"].mean()),
            "ap_M4": a1, "ap_M1": a0, "dap": a1 - a0,
        }
        log(f"    {name}: n={len(sub)} n_pos={int(sub['y'].sum())} dAP={a1-a0:+.6f}")

    # reported A5 (if the final summary.json carries it)
    a5 = ((summary or {}).get("adversarial", {}) or {}).get("A5_attribution_strata")
    res["reported_in_summary"] = a5
    res["present_in_summary"] = bool(a5)
    if a5:
        for k, v in a5.items():
            if isinstance(v, dict) and v.get("dap") is not None:
                mine = res["strata"].get(k, {}).get("dap")
                if mine is not None:
                    res.setdefault("deltas_vs_reported", {})[k] = float(mine) - float(v["dap"])
    else:
        res["status"] = ("A5 not present in the summary.json this verifier read -> "
                         "reported values NOT VERIFIED (independent recomputation above stands)")
    return res


