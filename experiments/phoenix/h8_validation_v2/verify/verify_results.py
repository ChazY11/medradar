def wait_for(paths, timeout_s=1500, poll_s=20):
    """Bounded polling loop; returns {path: exists}."""
    t0 = time.time()
    missing = [p for p in paths if not Path(p).exists()]
    while missing and time.time() - t0 < timeout_s:
        log(f"  waiting {int(time.time()-t0)}s for: {[p.name for p in missing]}")
        time.sleep(poll_s)
        missing = [p for p in missing if not Path(p).exists()]
    return {Path(p).name: Path(p).exists() for p in paths}


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest().upper()


def deep_find(obj, key_pred, path=()):
    """Yield (path, value) for every dict key satisfying key_pred."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if key_pred(str(k)):
                yield path + (str(k),), v
            yield from deep_find(v, key_pred, path + (str(k),))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from deep_find(v, key_pred, path + (str(i),))


def find_first(obj, names, pred=None):
    """First value whose key is in names (case-insensitive) and passes pred."""
    want = {n.lower() for n in names}
    for p, v in deep_find(obj, lambda k: k.lower() in want):
        if pred is None or pred(v):
            return ".".join(p), v
    return None, None


