def verdict_from_gates(g: dict, dap: float, tau: float = 0.03) -> dict:
    """Apply the frozen protocol section 8 mapping mechanically.

    Gate semantics follow the protocol table:
      G1  dAP >= tau                     G1b bootstrap CI low > 0
      G2  track38 dAP >= 0.02            G3  placebo p < 0.05
      G4  active dAP >= 0.02             G5  n_pos >= 100
      G6  CI upper >= tau  (tau NOT excluded)
      G7  low-base positive share <= 0.5
    """
    g1, g1b, g2, g3, g4, g5, g6, g7 = (g.get(k) for k in
                                       ("G1", "G1b", "G2", "G3", "G4", "G5", "G6", "G7"))
    if g5 is False:
        return {"verdict": "INCONCLUSIVE", "reason": "G5 false (n_pos < 100)"}
    if g1 is None or g1b is None:
        return {"verdict": "UNKNOWN", "reason": "primary gates not evaluable"}
    if g1 and g1b:
        failing = [k for k in ("G2", "G3", "G4", "G7") if g.get(k) is False]
        if not failing:
            return {"verdict": "GO", "reason": "all of G1,G1b,G2,G3,G4,G5,G7 hold"}
        return {"verdict": "LIMITED GO", "reason": f"G1&G1b hold but failing: {failing}"}
    # --- below here G1 and/or G1b fails -> cannot be GO / LIMITED GO
    if g6 is False:
        return {"verdict": "NO-GO", "reason": "NO-GO branch 1: CI upper < tau, tau excluded"}
    if (0.0 < dap < tau) and g1b is True:
        return {"verdict": "NO-GO", "reason": "NO-GO branch 2: 0 < dAP < tau with CI low > 0 "
                                              "(statistically positive, below practical threshold)"}
    if g3 is False and g7 is False:
        return {"verdict": "NO-GO", "reason": "NO-GO branch 3: G3 and G7 both fail (structural artifact)"}
    return {"verdict": "INCONCLUSIVE", "reason": "CI spans 0 or tau; not separable"}


