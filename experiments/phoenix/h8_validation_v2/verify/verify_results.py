def region_sum(A, k):
    """Trailing window sum with min_periods=1, along axis 1."""
    T, Q = A.shape
    Cs = np.concatenate([np.zeros((T, 1)), np.cumsum(A, axis=1)], axis=1)
    idx = np.arange(Q)
    lo = np.maximum(idx - k + 1, 0)
    return Cs[:, idx + 1] - Cs[:, lo]


def region_sumsq(A, k):
    return region_sum(A * A, k)


def build_sim_features(X, P):
    """Own B1 + H8 feature builders, mirroring the protocol definitions.

    X = device event counts (tracks x quarters), P = pma counts.
    10 trailing history features + exposure, then 7 growth features.
    """
    T, Q = X.shape
    f = {}
    f["sum1"] = region_sum(X, 1)
    f["sum2"] = region_sum(X, 2)
    f["sum4"] = region_sum(X, 4)
    f["sum8"] = region_sum(X, 8)
    f["sum12"] = region_sum(X, 12)
    f["cum"] = np.cumsum(X, axis=1)
    f["mean4"] = f["sum4"] / 4.0
    n8 = np.minimum(8, np.arange(Q) + 1).astype(float)
    s8, ss8 = region_sum(X, 8), region_sumsq(X, 8)
    var8 = (ss8 - s8 ** 2 / n8) / np.maximum(n8 - 1, 1)
    var8[:, :2] = np.nan               # min_periods=3
    f["std8"] = np.sqrt(np.clip(var8, 0, None))
    f["accel"] = _shift(f["sum2"], 2)
    f["accel"] = (f["sum2"] - f["accel"]) / np.maximum(f["accel"], 1.0)
    f["log4"] = np.log1p(f["sum4"])
    f["exposure_q"] = np.tile(np.arange(Q)[None, :] + 1.0, (T, 1))
    f["log_exposure"] = np.log1p(f["exposure_q"])
    b1 = ["sum1", "sum2", "sum4", "sum8", "sum12", "cum", "mean4", "std8",
          "accel", "log4", "exposure_q", "log_exposure"]
    g = {}
    for w in (1, 2, 4, 8):
        cur = region_sum(X, w)
        prev = _shift(cur, w)
        g[f"growth{w}"] = (cur - prev) / (prev + 1.0)
    Y = np.log1p(X)
    xc = np.arange(12.0) - 5.5
    den = float((xc ** 2).sum())
    slope = np.full((T, Q), np.nan)
    for q in range(11, Q):
        slope[:, q] = (Y[:, q - 11:q + 1] @ xc) / den
    g["slope12"] = slope
    g["pma_share4"] = region_sum(P, 4) / (f["sum4"] + 1.0)
    g["volatility8"] = f["std8"] / (f["mean4"] + 1.0)
    h8 = b1 + ["growth1", "growth2", "growth4", "growth8", "slope12",
               "pma_share4", "volatility8"]
    return (np.stack([f[c] for c in b1], axis=2),
            np.stack([g[c] for c in (h8[len(b1):])], axis=2), b1, h8[len(b1):], f)


def _shift(A, k):
    out = np.zeros_like(A)
    if k < A.shape[1]:
        out[:, k:] = A[:, :-k]
    return out


def fit_logit(Xtr, ytr, Xte):
    """Same estimator family as the study: median impute -> standardise -> L2 logit C=1."""
    keep = []
    for j in range(Xtr.shape[1]):
        col = Xtr[:, j]
        fin = np.isfinite(col)
        if fin.sum() < 5 or np.nanstd(col[fin]) == 0:
            continue
        keep.append(j)
    if not keep or len(np.unique(ytr)) < 2:
        return np.full(len(Xte), float(np.mean(ytr)))
    Xtr, Xte = Xtr[:, keep], Xte[:, keep]
    pipe = make_pipeline(SimpleImputer(strategy="median"), StandardScaler(),
                         LogisticRegression(C=1.0, max_iter=2000, solver="lbfgs"))
    pipe.fit(Xtr, ytr)
    return pipe.predict_proba(Xte)[:, 1]


def sim_universe(rng, mu, phi, pma_share, Q=90, kind="nb"):
    """Simulate memoryless counts for one universe: per-track constant mean."""
    T = len(mu)
    if kind == "nb":
        # NB2 with Var = mu + phi*mu^2, drawn iid per track-quarter
        n = (1.0 / phi)[:, None]
        p = (n / (n + mu[:, None]))
        X = rng.negative_binomial(n=np.broadcast_to(n, (T, Q)),
                                  p=np.broadcast_to(p, (T, Q))).astype(float)
    else:                                        # Poisson variant
        X = rng.poisson(np.broadcast_to(mu[:, None], (T, Q))).astype(float)
    P = rng.binomial(X.astype(np.int64), np.broadcast_to(pma_share[:, None], (T, Q))).astype(float)
    return X, P


def sim_dap(X, P, years=range(2014, 2026), ceil_term=1):
    """Walk-forward purged evaluable dAP on a simulated panel. Returns (dap, n, n_pos, prev)."""
    F_b1, F_g, _, _, _ = build_sim_features(X, P)
    T, Q = X.shape
    fwd4 = np.full((T, Q), np.nan)
    if Q >= 5:
        fwd4[:, :Q - 4] = region_sum(X, 4)[:, 4:]
    trail8 = region_sum(X, 8)
    with np.errstate(invalid="ignore", divide="ignore"):
        y = ((fwd4 >= 3) & (fwd4 / 4.0 >= 1.5 * (trail8 / 8.0))).astype(float)
    y[~np.isfinite(fwd4)] = np.nan
    y = y.ravel()
    qgrid = np.tile(np.arange(Q)[None, :], (T, 1)).ravel()

    scores_b1, scores_h8, ys = [], [], []
    purge = 4 + ceil_term + 1
    for Y in years:
        qfirst = (Y - 2004) * 4
        if qfirst >= Q:
            continue
        qsel = [q for q in (qfirst, qfirst + 1, qfirst + 2, qfirst + 3) if q <= Q - 5]
        if not qsel:
            continue
        te = np.isin(qgrid, qsel)
        tr = (qgrid <= qfirst - purge) & np.isfinite(y)
        if te.sum() == 0 or tr.sum() == 0:
            continue
        ytr = y[tr]
        if len(np.unique(ytr)) < 2:
            continue
        Xtr_b1, Xte_b1 = F_b1.reshape(T * Q, -1)[tr], F_b1.reshape(T * Q, -1)[te]
        s1 = fit_logit(Xtr_b1, ytr, Xte_b1)
        Xtr_h8 = np.concatenate([Xtr_b1, F_g.reshape(T * Q, -1)[tr]], axis=1)
        Xte_h8 = np.concatenate([Xte_b1, F_g.reshape(T * Q, -1)[te]], axis=1)
        s2 = fit_logit(Xtr_h8, ytr, Xte_h8)
        scores_b1.append(s1); scores_h8.append(s2); ys.append(y[te])
    if not scores_b1:
        return None
    yall = np.concatenate(ys)
    s1 = np.concatenate(scores_b1); s2 = np.concatenate(scores_h8)
    if yall.sum() == 0:
        return None
    dap = average_precision_score(yall, s2) - average_precision_score(yall, s1)
    return {"dap": float(dap), "n": int(len(yall)), "n_pos": int(yall.sum()),
            "prevalence": float(yall.mean()),
            "ap_b1": float(average_precision_score(yall, s1)),
            "ap_h8": float(average_precision_score(yall, s2))}


def part5_null(d_primary: pd.DataFrame, observed_dap: float, N=20, seed0=987654321):
    log("[part5] independent matched-prevalence pure-noise null calibration")
    # observed per-track device means and dispersion (derived from trail8 rolling sums)
    g = d_primary.groupby("track_id")
    mu = (g["trail8_total"].mean() / 8.0).to_numpy(float)
    v8 = g["trail8_total"].var().to_numpy(float)
    varx = v8 / 8.0                       # iid: Var(rolling-8 sum) = 8 * Var(x)
    phi_raw = (varx - mu) / np.maximum(mu, 1e-9) ** 2
    phi = np.clip(phi_raw, 0.02, 4.0)
    T = len(mu)
    pma_share = np.full(T, 0.35)          # documented approximation, see limitations
    Q = 90

    # ---- calibrate the mean scalar so simulated evaluable prevalence matches real.
    # NOTE (verifier finding): Y1 = (fwd4>=3) & (fwd4_mean >= 1.5*trail8_mean) is
    # (almost) scale-invariant in the count level: scaling every count by s scales both
    # sides of the ratio. Only the fwd4_total>=3 term responds, and only for very small
    # counts. Therefore prevalence is only weakly controllable by a mean scalar; we do a
    # bounded grid search and report the residual mismatch instead of pretending success.
    target_prev = float(d_primary["y"].mean())
    grid = [0.60, 0.75, 0.90, 1.00, 1.15, 1.35, 1.60]
    calib = []
    best = (1.0, 1e9, None)
    for s_try in grid:
        rng = np.random.default_rng(seed0)
        prevs = []
        for _ in range(4):
            X, P = sim_universe(rng, mu * s_try, phi, pma_share, Q=Q, kind="nb")
            r = sim_dap(X, P)
            if r:
                prevs.append(r["prevalence"])
        prev = float(np.mean(prevs)) if prevs else float("nan")
        err = abs(prev - target_prev) if np.isfinite(prev) else 1e9
        calib.append({"scalar": s_try, "sim_prevalence": prev, "abs_err": err})
        log(f"    calib scalar={s_try:.2f} sim_prev={prev:.4f} target={target_prev:.4f} err={err:.4f}")
        if err < best[1]:
            best = (s_try, err, prev)
    s, calib_err, calib_prev = best

    out = {"target_prevalence_real": target_prev,
           "calibration_trace": calib,
           "calibrated_mean_scalar": s,
           "calibrated_sim_prevalence": calib_prev,
           "calibration_abs_error": calib_err,
           "prevalence_matched": bool(calib_err < 0.005),
           "scalar_insensitivity_finding":
               "simulated prevalence varies little with the mean scalar ("
               f"{min(c['sim_prevalence'] for c in calib):.3f}.."
               f"{max(c['sim_prevalence'] for c in calib):.3f} over scalar "
               f"{grid[0]}..{grid[-1]}), because Y1 is scale-invariant in the count level; "
               "exact matched prevalence is therefore NOT achieved and the null comparison "
               "is approximate on this dimension",
           "N_universes": N, "Q_quarters": Q,
           "n_tracks": T, "mu_sum": float(mu.sum()),
           "phi_median": float(np.median(phi_raw)),
           "phi_used_range": [float(phi.min()), float(phi.max())]}

    for kind in ("nb", "poisson"):
        rng = np.random.default_rng(seed0 + (7 if kind == "nb" else 13))
        das, prevs, ns, nposs = [], [], [], []
        for u in range(N):
            X, P = sim_universe(rng, mu * s, phi, pma_share, Q=Q, kind=kind)
            r = sim_dap(X, P)
            if r is None:
                continue
            das.append(r["dap"]); prevs.append(r["prevalence"]); ns.append(r["n"]); nposs.append(r["n_pos"])
        das = np.array(das)
        ge = int((das >= observed_dap).sum())
        out[kind] = {
            "n_universes": int(len(das)),
            "dap_mean": float(das.mean()), "dap_sd": float(das.std(ddof=1)),
            "dap_min": float(das.min()), "dap_max": float(das.max()),
            "dap_p50": float(np.percentile(das, 50)),
            "dap_p90": float(np.percentile(das, 90)),
            "dap_p95": float(np.percentile(das, 95)),
            "sim_prevalence_mean": float(np.mean(prevs)),
            "sim_n_mean": float(np.mean(ns)),
            "sim_n_pos_mean": float(np.mean(nposs)),
            "observed_dap": float(observed_dap),
            "z_vs_null": float((observed_dap - das.mean()) / das.std(ddof=1)),
            "n_null_ge_observed": ge,
            "upper_tail_p": float((1 + ge) / (len(das) + 1)),
            "percentile_of_observed": float(100.0 * (das < observed_dap).mean()),
            "null_dap_values": [float(x) for x in das],
        }
        log(f"    {kind}: null dAP mean={das.mean():.6f} sd={das.std(ddof=1):.6f} "
            f"p95={np.percentile(das,95):.6f} obs={observed_dap:.6f} z={out[kind]['z_vs_null']:.2f} "
            f"tail_p={out[kind]['upper_tail_p']:.3f}")
    return out


