def part2_bootstrap(d: pd.DataFrame, seeds=(20261109, 1, 7, 42, 2024), B=1000):
    """Paired cluster bootstrap over track_id, own RNG, independent implementation."""
    log("[part2] paired cluster bootstrap over track_id")
    tracks = np.array(sorted(d["track_id"].unique()))
    tid = d["track_id"].to_numpy()
    y = d["y"].to_numpy(float)
    s_m1 = d["M1_persistence"].to_numpy(float)
    s_m4 = d["M4_h8_growth"].to_numpy(float)
    # index groups once
    pos_by_track = {t: np.flatnonzero(tid == t) for t in tracks}
    out = {}
    all_lo, all_hi, all_pt = [], [], []
    for seed in seeds:
        rng = np.random.default_rng(seed)
        diffs = np.empty(B)
        for b in range(B):
            draw = rng.choice(tracks, size=len(tracks), replace=True)
            idx = np.concatenate([pos_by_track[t] for t in draw])
            yy = y[idx]
            if yy.sum() == 0 or yy.sum() == len(yy):
                diffs[b] = np.nan
                continue
            diffs[b] = average_precision_score(yy, s_m4[idx]) - average_precision_score(yy, s_m1[idx])
        ok = diffs[np.isfinite(diffs)]
        lo, hi = np.percentile(ok, [2.5, 97.5])
        out[str(seed)] = {"B": int(B), "n_valid": int(ok.size), "mean": float(ok.mean()),
                          "sd": float(ok.std(ddof=1)), "ci95": [float(lo), float(hi)],
                          "p_one_sided_le0": float((ok <= 0).mean())}
        all_lo.append(float(lo)); all_hi.append(float(hi)); all_pt.append(float(ok.mean()))
        log(f"    seed={seed}: mean={ok.mean():.6f} sd={ok.std(ddof=1):.6f} "
            f"CI=[{lo:.6f},{hi:.6f}] n_valid={ok.size}")
    # consensus across seeds
    cons = {
        "seeds": list(seeds),
        "ci95_low_min": float(min(all_lo)),
        "ci95_low_max": float(max(all_lo)),
        "ci95_high_min": float(min(all_hi)),
        "ci95_high_max": float(max(all_hi)),
        "boot_mean_range": [float(min(all_pt)), float(max(all_pt))],
    }
    return {"per_seed": out, "across_seeds": cons}


