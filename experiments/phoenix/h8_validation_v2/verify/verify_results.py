def _verdict_match(reported: str, mapped: str) -> bool:
    r = reported.upper().replace("-", " ").replace("_", " ").strip()
    m = mapped.upper().replace("-", " ").replace("_", " ").strip()
    if m == "LIMITED GO":
        return r.startswith("LIMITED")
    if m == "NO GO":
        return r.startswith("NO GO") or r.startswith("NOGO")
    return r.startswith(m.split()[0])


