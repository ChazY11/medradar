"""Generate experiments/b040/REPORT.md from lag_analysis.json (no hand-typed numbers)."""
from __future__ import annotations

import json
from pathlib import Path

BASE = Path("experiments/b040")


def num(value, digits: int = 3) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "—"


def main() -> int:
    data = json.loads((BASE / "lag_analysis.json").read_text(encoding="utf-8"))
    design = data["design"]
    coverage = data["coverage"]
    profile = data["lag_profile"]
    lags = design["lags"]
    best = data["best_lag"]

    lines: list[str] = []
    add = lines.append
    add("# Independent confirmation, first attempt: device trials vs regulatory clearances")
    add("")
    add("Generated by `write_report.py` from `lag_analysis.json`; no number is typed by hand. "
        "Analysis pre-declared in DECISIONS D-022 **before** the association was computed; "
        "collection described in D-022 and `collect.log`.")
    add("")
    add("## Why this exists")
    add("")
    add("Cycle 4 measured that the shipped data spine contains no source able to confirm a detected "
        "regulatory change: the only other registry present (ClinicalTrials.gov) is mapped to drug "
        "tracks, disjoint from the device tracks (0 of 104 cells). B-040 closed that gap by "
        "collecting device trials into a **new, disposable** database, leaving the frozen research "
        "lane untouched.")
    add("")
    add("## What the new lane is")
    add("")
    add("* ClinicalTrials.gov API v2, interventional studies, window matching the detection lane "
        "(2016-09 … 2026-10); knowledge time = study first-posted date.")
    add("* Sponsored by the curated 51-company device watchlist; sponsor resolution and device-track "
        "mapping reuse the repository's audited collector rather than a parallel implementation.")
    add("* Bounded run: 82 sponsor terms, 107 requests, 0 errors, no truncation reported by the "
        "collector's own caps.")
    add("* 4,130 studies returned → 2,663 interventional studies in window → **2,663 trial events**; "
        "1,472 (55 %) attributable to a curated company, 1,278 (48 %) mapped to a device track, "
        "1,181 device-intervention studies with a device track, 43 distinct device tracks.")
    add("")
    add("## The test")
    add("")
    add(f"Cells are (curated company, device track) pairs carrying both lanes, subject to "
        f"pre-registered floors of ≥{design['min_regulatory_events']} regulatory events and "
        f"≥{design['min_trial_events']} trial events.")
    add("")
    add(f"* {coverage['cells_in_both_lanes']} cells exist in both lanes; "
        f"**{coverage['cells_eligible']} pass the floors** "
        f"({coverage['regulatory_events_eligible']} regulatory + "
        f"{coverage['trial_events_eligible']} trial events).")
    add(f"* Statistic: cross-correlation at lags {lags[0]} … {lags[-1]} months "
        f"({design['lag_sign_convention']}).")
    add(f"* Pooled by Fisher z; null distribution from circularly shifting each cell's trial series "
        f"({design['null_shifts']} shifts, seed {design['seed']}), which preserves every series' own "
        f"autocorrelation and volume and destroys only the cross-series alignment.")
    add("")
    add("## Result: no detectable association at any lag")
    add("")
    add("| lag (months) | cells | observed pooled r | null 95 % interval |")
    add("|---:|---:|---:|---|")
    for lag in lags:
        block = profile[str(lag)]
        add(f"| {lag:+d} | {block['cells']} | {num(block['observed'])} | "
            f"[{num(block['null_low'])}, {num(block['null_high'])}] |")
    add("")
    add(f"The entire lag profile lies inside the null interval. The largest observed value is "
        f"{num(profile[str(best)]['observed'])} at lag {best:+d} months, against a null band of "
        f"[{num(profile[str(best)]['null_low'])}, {num(profile[str(best)]['null_high'])}] — not a "
        f"signal at any conventional threshold, and not a peak that stands out from its neighbours.")
    add("")
    add("## What this licenses, and what it does not")
    add("")
    add("**Licensed.** At the (company, device track) granularity these two independent lanes carry "
        "**no detectable aligned time structure** in either direction between 6 months before and 12 "
        "months after a regulatory event. Any claim that device-trial activity and clearance activity "
        "confirm one another at cell level is unsupported by this test, including the "
        "\"evidence fusion\" claim that motivated collecting the lane.")
    add("")
    add("**Not licensed.** This is *not* evidence that trials and clearances are unrelated. Three "
        "limits dominate:")
    add("")
    add(f"* **Coverage.** 26 cells exist in both lanes and only {coverage['cells_eligible']} clear the "
        f"activity floors. Sponsor resolution covers 55 % of returned studies and device-track "
        f"mapping 48 %; the lane is a bounded sample, not a census.")
    add("* **Sparsity.** Per-cell series are dominated by zero months (the floors are 6 and 3 events "
        "over 119 months), so a per-cell correlation is mostly a co-occurrence pattern of rare "
        "months rather than a rate relationship.")
    add("* **Granularity.** Trials attach to a company, not to a legal sub-entity, so a company with "
        "many subsidiaries may have trials and clearances recorded at different entities and still "
        "be pooled into one cell; conversely, the track mapping of a trial is keyword-based.")
    add("")
    add("## Consequence for the programme")
    add("")
    add("The independent-confirmation question is now **answerable in principle but unanswerable in "
        "practice with this sample**: the lane exists and is committed, the test is pre-registered "
        "and re-runnable, and the answer at this granularity is null. Getting a real answer requires "
        "either (a) much denser independent evidence per cell — hiring and patents are the two "
        "declared gaps — or (b) a different unit of analysis, such as company-level entry cohorts "
        "rather than cell-level monthly counts. Both are backlog items, not conclusions.")
    add("")
    add("## Reproduction")
    add("")
    add("```bash")
    add("cd D:\\DEPPSKK\\worktrees\\integration-v2")
    add("$env:PYTHONIOENCODING=\"utf-8\"")
    add("python experiments/b040/collect_device_trials.py   # bounded; writes data/b040_device_trials.sqlite")
    add("python experiments/b040/lag_analysis.py")
    add("python experiments/b040/write_report.py")
    add("```")
    add("")
    (BASE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {BASE / 'REPORT.md'} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
