"""Generate experiments/detect_v1/REPORT.md from the frozen artifacts.

Every number is read from a committed JSON artifact; none is typed by hand.
Regenerate with:

    python experiments/detect_v1/write_report.py
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

BASE = Path("experiments/detect_v1")


def load(name: str) -> Any:
    return json.loads((BASE / name).read_text(encoding="utf-8"))


def pct(value: Any, digits: int = 1) -> str:
    return f"{value * 100:.{digits}f}%" if isinstance(value, (int, float)) else "—"


def num(value: Any, digits: int = 3) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "—"


def main() -> int:
    bench = load("benchmark.json")
    streams = load("streams.json")
    real = load("realdetect.json")
    assignment = load("track_assignment_audit.json")
    reassign = load("reassignment_audit.json")
    design = bench["design"]
    levels = bench["levels"]
    primary = levels["track"]
    counts = streams["counts"]
    budget = primary["paired_comparison"]["budget"]
    readout = primary["frontier_readout"][str(budget)]
    paired_cmp = primary["paired_comparison"]["comparisons"]
    naive_best = readout["naive_multiplier"]["detection_probability"]

    lines: list[str] = []
    add = lines.append

    add("# Cycle 3 — OBSERVE layer: can a technology change be detected early and honestly?")
    add("")
    add("Generated by `experiments/detect_v1/write_report.py` from the artifacts in this "
        "directory. No number below is typed by hand.")
    add("")
    add("## 0. Verdict")
    add("")
    add(f"**The simple baseline is not beaten, and that is the result.** On the primary "
        f"panel, inside a matched false-alarm budget of {pct(budget,0)} per stream, the naive "
        f"rate-multiplier alert detects {num(naive_best)} of injected sustained rate changes, "
        f"while the best likelihood detector reaches only "
        f"{num(readout['poisson_cusum']['detection_probability'])} (Poisson CUSUM) and the "
        f"Poisson Bayes factor {num(readout['poisson_bayes_factor']['detection_probability'])}. "
        f"The paired, entity-clustered differences versus the naive baseline are **negative**:")
    add("")
    add("| detector | Δ detection vs naive | 95% clustered CI | excludes zero |")
    add("|---|---:|---|---|")
    for name, comparison in paired_cmp.items():
        add(f"| {name} | {comparison['difference']:+.3f} | "
            f"[{comparison['ci_low']:+.3f}, {comparison['ci_high']:+.3f}] | "
            f"{comparison['excludes_zero']} |")
    add("")
    add(f"So the programme's recurring lesson repeats one layer down: **a well-matched simple "
        f"test is hard to beat**, and buying complexity before fixing data density buys "
        f"nothing. Absolute detection is low in every case — even the best detector misses "
        f"most 2× shifts — and the binding constraint is the sparsity of the lane, not the "
        f"algorithm.")
    add("")
    add("**A caveat that constrains how far this can be pushed.** Injected shifts are abrupt, "
        "permanent, multiplicative changes to a Poisson rate. That is precisely the alternative a "
        "matched rate-ratio test is optimised for, and it is also the model in which CUSUM theory "
        "expects a likelihood detector to win. The injection therefore works as a **positive "
        "control**, not as a falsification test of the likelihood approach: the finding is narrow "
        "and is stated narrowly — *for abrupt multiplicative step changes on this lane, the simple "
        "test is at least as good*. Ramp, transient and heterogeneous alternatives are untested "
        "(backlog B-026). A full design review with kill conditions is in "
        "`docs/research/DETECTION_DESIGN_REVIEW.md`.")
    add("")

    add("## 1. What this cycle was for")
    add("")
    add("The mission was realigned to Observe → Understand → Anticipate, with "
        "technology-change detection as the new P1 behind the scientific-reliability floor P0; "
        "the forecasting programme was preserved at P3. This cycle builds the OBSERVE layer's "
        "first real capability: detecting a sustained change in a company's rate of technology "
        "activity on sparse monthly counts, with false alarms controlled and stated. The design "
        "was pre-registered in `research/DECISIONS.md` D-013/D-014 before any result existed, "
        "and two harness defects found during execution are disclosed in D-015/D-016.")
    add("")

    add("## 2. The data, and why it constrains everything")
    add("")
    add("Material events (510(k) clearances plus original / PANEL-TRACK PMA) from the frozen "
        "research lane, grouped by the deterministic legal-entity universe (no fuzzy matching) "
        f"into monthly counts over {streams['window']['start']} … {streams['window']['end']}.")
    add("")
    add("| granularity | cells | entities | groups | events | median events/cell | median zero months |")
    add("|---|---:|---:|---:|---:|---:|---:|")
    for key, label in (("track_level", "entity × track (primary)"),
                       ("track_level_clean", "entity × track, deterministic track only"),
                       ("domain_level", "entity × domain")):
        block = counts[key]
        add(f"| {label} | {block['cells']} | {block['entities']} | {block['groups']} | "
            f"{block['events']} | {block['events_per_cell']['median']} | "
            f"{block['zero_months_median']}/{streams['window']['months']} |")
    add("")
    add(f"Eligibility (pre-registered): ≥{streams['eligibility']['min_total_events']} material "
        f"events and ≥{streams['eligibility']['min_active_months']} active months per cell.")
    add("")
    add("A typical analysable cell has ~25 events over 120 months and is zero in ~98 of them: "
        "about **0.2 events per month**. A 2× rate increase moves the expectation from 0.2 to "
        "0.4 events per month, which no single month can distinguish from noise. This is why "
        "detection delay and detection probability dominate every table below.")
    add("")

    add("## 3. Noise control: is the technology dimension itself trustworthy?")
    add("")
    add(f"Track assignment provenance, audited before the benchmark: "
        f"**{assignment['events_explicit_code_map']} of {assignment['events_total']}** events "
        f"({pct(assignment['events_explicit_code_map']/assignment['events_total'])}) get their "
        f"track from the deterministic `{{product_code: track_id}}` map; "
        f"**{assignment['events_text_keyword_fallback']}** "
        f"({pct(assignment['fraction_keyword'])}) come from device-text keyword matching. All "
        f"{assignment['codes_multi_track']} product codes that land in more than one track are in "
        f"that fallback set. Keyword assignment is not deterministic per code, so a wording "
        f"change can move events between cells and manufacture an apparent change — which is why "
        f"a deterministic-track-only sensitivity level exists.")
    add("")
    add(f"Second check: {reassign['cells_complete_relabelling']} of "
        f"{reassign['cells_checked']} cells with ≥12 events replace their product-code "
        f"composition completely between their early and late halves, so wholesale relabelling "
        f"is rare but not absent.")
    add("")

    add("## 4. Benchmark design")
    add("")
    add(f"* Real monthly stream shapes preserved; a sustained rate multiplier "
        f"({', '.join(str(m) for m in design['multipliers'])}×) applied at onsets "
        f"{design['onsets']}; post-onset counts re-drawn from a Poisson law at the injected rate, "
        f"so injected streams are as noisy as real ones.")
    add(f"* A detection is credited inside "
        f"[onset − {design['onset_tolerance_months']}, onset + {design['horizon_months']}] "
        f"months. The one-month pre-onset tolerance is applied identically to every detector so "
        f"that a detector reporting its estimated change point is not penalised for landing just "
        f"before the truth.")
    add("* Cells are split by entity hash into halves; **all reported numbers come from the "
        "held-out half** and no entity appears in both.")
    add("* Injection seeds depend only on (cell, onset, multiplier), never on the detector, so "
        "every detector scores the **identical** injected series. Comparisons are therefore "
        "**paired**, and their intervals resample **entities**, not trials.")
    add("* The **entire false-alarm/detection frontier** is reported for every detector, one "
        "point per sensitivity knob. No single threshold is hidden behind a calibration step "
        "(an earlier single-point calibration proved unstable on ~50 cells — DECISIONS D-016).")
    add("")

    add("## 5. Frontier results")
    add("")
    for level_key, label in (("track", "Primary: entity × track"),
                             ("track_clean", "Sensitivity: deterministic tracks only"),
                             ("domain", "Sensitivity: entity × domain")):
        block = levels[level_key]
        add(f"### {label}")
        add("")
        add(f"{block['evaluation_cells']} evaluation cells, {block['evaluation_entities']} "
            f"entities, {block['shift_trials']} injected shift trials, "
            f"{block['spike_trials']} spike trials.")
        add("")
        add("| detector | knob range | FPR span | P(detect) at 1% | at 2% | at 5% |")
        add("|---|---|---|---:|---:|---:|")
        readouts = {far: block["frontier_readout"][far] for far in
                    ("0.01", "0.02", "0.05")}
        for name, entry in block["detectors"].items():
            if "frontier" not in entry:
                continue
            points = entry["frontier"]
            knobs = [point["knob"] for point in points]
            fars = [point["false_alarm_rate"] for point in points
                    if point["false_alarm_rate"] is not None]
            cells = []
            for far in ("0.01", "0.02", "0.05"):
                chosen = readouts[far].get(name, {})
                cells.append(num(chosen.get("detection_probability")) if "detection_probability" in chosen
                             else "—")
            add(f"| {name} | {min(knobs):g}–{max(knobs):g} | "
                f"{pct(min(fars)) if fars else '—'}–{pct(max(fars)) if fars else '—'} | "
                f"{cells[0]} | {cells[1]} | {cells[2]} |")
        add("")
        paired_block = block["paired_comparison"]["comparisons"]
        if paired_block:
            add(f"Paired comparison against the naive baseline inside the same {pct(block['paired_comparison']['budget'],0)} "
                f"budget (picked knobs: {block['paired_comparison']['picked_knobs']}):")
            add("")
            add("| detector | Δ detection | 95% clustered CI | excludes zero |")
            add("|---|---:|---|---|")
            for name, comparison in paired_block.items():
                add(f"| {name} | {comparison['difference']:+.3f} | "
                    f"[{comparison['ci_low']:+.3f}, {comparison['ci_high']:+.3f}] | "
                    f"{comparison['excludes_zero']} |")
            add("")
    add("**How to read this.** The naive rate-multiplier is the strongest detector at every "
        "reported false-alarm budget on the primary panel and on the domain panel. On the "
        "deterministic-track-only panel the Bayes factor edges ahead "
        f"({levels['track_clean']['paired_comparison']['comparisons']['poisson_bayes_factor']['difference']:+.3f}, "
        f"CI "
        f"[{levels['track_clean']['paired_comparison']['comparisons']['poisson_bayes_factor']['ci_low']:+.3f}, "
        f"{levels['track_clean']['paired_comparison']['comparisons']['poisson_bayes_factor']['ci_high']:+.3f}]) "
        "— so the likelihood advantage exists but is not stable across panels, and it is the "
        "only place in three granularities where a likelihood detector wins. A fair summary is "
        "that the evidence **does not support preferring a likelihood detector** here.")
    add("")

    add("## 6. Per-magnitude behaviour (primary panel, 2 % budget)")
    add("")
    add("| detector | P(det) at 2× | at 3× | at 5× | median delay at 5× (months) |")
    add("|---|---:|---:|---:|---:|")
    for name, chosen in readout.items():
        if "by_multiplier" not in chosen:
            continue
        by = chosen["by_multiplier"]
        add(f"| {name} | {num(by['2.0']['detection_probability'])} | "
            f"{num(by['3.0']['detection_probability'])} | {num(by['5.0']['detection_probability'])} | "
            f"{num(by['5.0']['median_delay_months'],0)} |")
    add("")
    add("Detection is respectable only for large shifts. A 2× change in this lane is close to "
        "undetectable at an honest alarm budget regardless of detector — which is a statement "
        "about the data, not only about the algorithms.")
    add("")

    add("## 7. Spike versus sustained change")
    add("")
    add("A single-month spike was injected with the same multipliers; declaring a spike to be a "
        "sustained change is the operational false positive that matters.")
    add("")
    add("| detector | spike declared at 2× | at 3× | at 5× |")
    add("|---|---:|---:|---:|")
    for name, chosen in readout.items():
        if "spike_false_change_rate" not in chosen:
            continue
        spike = chosen["spike_false_change_rate"]
        add(f"| {name} | {num(spike.get('2.0'))} | {num(spike.get('3.0'))} | "
            f"{num(spike.get('5.0'))} |")
    add("")
    add("**Inconclusive, and reported as such.** On a ~0.2 events/month cell a one-month "
        "multiplier usually adds zero or one event, so the injection itself is barely "
        "distinguishable from the cell's own noise. The low rates therefore partly measure a weak "
        "injection. A real spike-versus-level-shift test needs denser streams (quarterly "
        "aggregation or larger cells) and is backlog B-026.")
    add("")

    add("## 8. Real data: alert volume, FDR control, and confirmation")
    add("")
    bh = real["hypothesis_test"]["bh"]
    add(f"Over {real['design']['cells_tested']} eligible cells, a single pre-declared per-cell "
        f"test (last 24 months vs the preceding 48 months, exact one-sided Poisson) rejects "
        f"**{bh['rejected']} cells** under Benjamini–Hochberg at q = {bh['q']} "
        f"(cut-off p = {num(bh['cutoff_pvalue'],5)}).")
    add("")
    add("| detector | alerts on the full panel | alerts that also survive BH | novelty share "
        "(alerted) | novelty share (control) |")
    add("|---|---:|---:|---:|---:|")
    for name, block in real["detectors"].items():
        if "alerts_total" not in block:
            continue
        nov = block["novelty_comparison"]
        add(f"| {name} | {block['alerts_total']} | {block['alerts_surviving_bh']} | "
            f"{num(nov['mean_novelty_share_alerted'])} | {num(nov['mean_novelty_share_control'])} |")
    add("")
    add("Two honest readings. First, the **alert volume is tiny** (0–2 alarms across 107 cells "
        "and a decade) because the operating point is deliberately conservative — the detector is "
        "a needle-finder, not a monitoring feed. Second, the **objective confirmation signal "
        "failed**: the share of post-alert product codes that are new relative to the previous "
        "three years is zero in both alerted and control cells, because most cells exercise only "
        "one or two codes. This check cannot discriminate at this granularity and is recorded as "
        "a failure, not as evidence that the changes are unreal.")
    add("")

    add("## 9. Negative results and what did not work")
    add("")
    add("- **The likelihood detectors did not beat the simple baseline** on the primary panel "
        "(all paired differences negative, intervals excluding zero). This contradicts the "
        "hypothesis that motivated the cycle and is the cycle's main finding.")
    add("- **Poisson CUSUM is not usable at an honest alarm budget.** It needs a threshold of 40 "
        "before its false-alarm rate is acceptable, at which point it detects ~17 %. At looser "
        "thresholds it reaches ~50 % detection but alarms on ~43 % of clean streams.")
    add("- **No detector detects small (2×) changes** in this lane at any honest budget.")
    add("- **The spike-versus-level-shift test could not be evaluated** because injected spikes "
        "are not distinguishable from baseline noise at this density.")
    add("- **The novelty confirmation signal is uninformative** at this granularity.")
    add("- **A single-point calibration design failed and was replaced** by a full frontier "
        "(DECISIONS D-016); the superseded numbers are recorded there.")
    add("")

    add("## 10. Limitations")
    add("")
    add("- Injected step changes are **not** real technology changes. The benchmark measures "
        "detection of a statistical rate shift; it does not establish that a detected shift is "
        "strategically meaningful. That is an Understand-layer judgement.")
    add("- Because injections multiply the baseline rate by a constant, a matched rate-ratio test "
        "is the *correct* model for this alternative. The naive detector's win is therefore partly "
        "a property of the injection design — real technology changes may ramp or be heterogeneous, "
        "which is exactly the regime where likelihood detectors are expected to help. The honest "
        "conclusion is narrow: **for abrupt, permanent, multiplicative shifts on this lane, the "
        "simple test is best**; ramp and heterogeneous alternatives are untested (backlog B-026).")
    add("- Cells are treated as independent; correlated company-wide or regulator-wide surges are "
        "not modelled, so real-world false alarms may exceed the measured rate.")
    add("- Uninjected cells can contain genuine level changes, so the measured false-alarm rate is "
        "an **upper bound** on detector noise (noted by the detector implementer).")
    add("- Real-data confirmation has **no independent ground truth**: both regulatory pathways "
        "come from the same filing system, and the novelty signature failed.")
    add("- Track assignment is deterministic for ~94 % of events; the 6 % keyword fallback is a "
        "real false-change channel. The clean variant shows the ranking is unchanged, not that the "
        "channel is harmless.")
    add("- The lane is left-censored at 2016-11; the taxonomy is not versioned by effective date.")
    add("- **The final calendar month is excluded** because the lane ends 2026-10-15 and a partial "
        "month is about half its normal volume, which manufactures an apparent drop. Even so, a "
        "lane-wide volume artifact is present at the boundary of the original data and was flagged "
        "by the independent design review; detectors are not seasonally adjusted (January runs "
        "about 14 % below the annual mean), and their false-alarm rates therefore include real "
        "artifact, not only statistical noise.")
    add("- **The naive comparator is undefined on a large share of the data in principle**: most "
        "stream-months have a zero trailing-12-month baseline. The shipped implementation guards "
        "this with a minimum observed-event rule, but any rate-ratio alert is fragile exactly where "
        "this lane is sparsest, and the comparison should be read with that in mind.")
    add("- **'Material' is not 'technical'.** About 15 % of the lane's 510(k)s are 'Special' "
        "510(k)s, i.e. modifications of the filer's own existing device rather than new technology. "
        "No filter separates them here, so a detected activity change may reflect device "
        "maintenance rather than a technology shift.")
    add("- **New product codes create churn.** Some recently created product codes account for a "
        "large share of recent activity in specific tracks, and a code that was unmapped earlier "
        "falls back to keyword assignment. This is a taxonomy-churn channel that can look like "
        "technology entry; it is documented by the design review and not yet controlled "
        "(backlog B-032).")
    add("- **No independent confirmation source exists in the current data spine.** The two "
        "regulatory pathways share a filing system, procurement rows are undated with "
        "`pit_usable=0`, publication counts are annual and cover 51 of the cohort entities, and "
        "there is no trials table. The 'is the change real' question is therefore **blocked, not "
        "answered**, and the design review marks it so.")
    add("- A detection is a statement about the rate of public regulatory activity. It is **not** "
        "evidence of intent, capability or internal R&D.")
    add("")

    add("## 11. Reproduction")
    add("")
    add("```bash")
    add("cd D:\\DEPPSKK\\worktrees\\integration-v2")
    add("$env:PYTHONIOENCODING=\"utf-8\"")
    add("python experiments/detect_v1/streams.py --db data/research.sqlite")
    add("python experiments/detect_v1/audit_track_assignment.py")
    add("python experiments/detect_v1/audit_reassignment.py")
    add("python experiments/detect_v1/benchmark.py")
    add("python experiments/detect_v1/realdetect.py --db data/research.sqlite")
    add("python experiments/detect_v1/write_report.py")
    add("```")
    add("")
    add(f"Input lane `data/research.sqlite`: {counts['material_events_total']} material events. "
        f"Design constants are recorded in `benchmark.json` under `design`.")
    add("")

    (BASE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {BASE / 'REPORT.md'} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
