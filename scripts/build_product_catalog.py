class _FactReader:
    """Read-only ``db.query`` / ``db.scalar`` adapter over SQLite.

    The production database is opened with ``mode=ro``: this generator must
    never mutate the facts table it is describing.
    """

    def __init__(self, connection: sqlite3.Connection, path: str) -> None:
        self.conn = connection
        self.path = path

    def query(self, sql: str, params=()) -> list[dict]:
        cursor = self.conn.execute(sql, tuple(params))
        columns = [column[0] for column in cursor.description]
        return [dict(zip(columns, row)) for row in cursor.fetchall()]

    def scalar(self, sql: str, params=(), default=None):
        row = self.conn.execute(sql, tuple(params)).fetchone()
        return row[0] if row is not None else default


@contextmanager
def open_facts(path: str | Path):
    """Open the facts database strictly read-only (``mode=ro``)."""
    resolved = Path(path).resolve()
    connection = sqlite3.connect(f"file:{resolved.as_posix()}?mode=ro", uri=True)
    try:
        yield _FactReader(connection, str(resolved))
    finally:
        connection.close()

