def _material_pma(payload_raw) -> bool:
    """Analysis-layer definition of a material PMA event.

    Mirrors ``medradar.analyze._is_material_pma``: an original PMA (no
    supplement number or ``S0``) or a Panel-Track supplement counts; routine
    administrative supplements (30-Day Notice, Real-Time Process, ...) do not.
    """
    try:
        payload = json.loads(payload_raw) if payload_raw else {}
    except (TypeError, ValueError):
        payload = {}
    if not isinstance(payload, dict):
        payload = {}
    number = str(payload.get("supplement_number") or "").strip().upper()
    supplement_type = str(payload.get("supplement_type") or "").strip().upper()
    if number in ("", "0", "S0"):
        return True
    return "PANEL TRACK" in supplement_type


def _valid_code(code: str) -> bool:
    return (
        code.strip().upper() not in families.INVALID_PRODUCT_CODES
        and code.replace("-", "").isalnum()
    )


def activity_counts(db) -> dict[str, int]:
    """Per-product-code counts in the analysis universe: 510(k) + material PMA.

    This is deliberately the same universe as ``medradar.analyze`` so the
    catalog ranking cannot drift away from the product-intel layer after a PMA
    backfill (which is exactly how the old "all events" ranking broke).
    """
    rows = db.query(
        "SELECT product_code, kind, payload FROM events"
        " WHERE product_code IS NOT NULL AND product_code != ''"
    )
    counts: dict[str, int] = {}
    for row in rows:
        code = str(row["product_code"]).strip()
        if not _valid_code(code):
            continue
        kind = str(row.get("kind") or "")
        if kind == "510k" or (kind == "pma" and _material_pma(row.get("payload"))):
            counts[code] = counts.get(code, 0) + 1
    return counts


def rank_top_codes(db, limit: int = TOP_N) -> list[tuple[str, int]]:
    """Top product codes by 510(k) + material-PMA volume (deterministic ties)."""
    counts = activity_counts(db)
    ranked = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
    return ranked[:limit]


def build_catalog(
    db, limit: int = TOP_N, existing: dict | None = None
) -> tuple[dict, dict]:
    """Build the merged Chinese catalog payload plus a coverage report.

    * ranking universe = 510(k) + material PMA (analysis layer);
    * entries already committed are kept even if they drop out of the top-N;
    * ``REVIEWED_CATALOG`` / ``EXTENDED_CATALOG`` always win over the old file,
      so the reviewed translations are never overwritten.
    """
    counts = activity_counts(db)
    ranked = sorted(counts.items(), key=lambda item: (-item[1], item[0]))[:limit]
    activity_total = sum(counts.values())
    previous = existing if existing is not None else (read_json(CATALOG_FILE) or {})
    if not isinstance(previous, dict):
        previous = {}
    code_rows = {
        str(row["product_code"]): row
        for row in db.query("SELECT product_code, device_name, definition FROM product_codes")
    }
    catalog: dict[str, dict[str, str]] = {}
    missing: list[str] = []
    reviewed_events = extended_events = 0
    reviewed_entries = extended_entries = 0
    for code, n in ranked:
        entry = REVIEWED_CATALOG.get(code)
        if entry:
            reviewed_entries += 1
            reviewed_events += n
        else:
            entry = EXTENDED_CATALOG.get(code)
            if entry:
                extended_entries += 1
                extended_events += n
        if entry:
            name_zh, definition_zh = entry
        else:
            missing.append(code)
            name_zh = str(code_rows.get(code, {}).get("device_name") or code)
            definition_zh = "（暂无中文说明）" + name_zh
        catalog[code] = {"name_zh": name_zh, "definition_zh": definition_zh}

    # keep previously catalogued codes that fell out of the new top-N
    retained_entries = 0
    for code in sorted(previous):
        if code in catalog:
            continue
        entry = REVIEWED_CATALOG.get(code) or EXTENDED_CATALOG.get(code)
        if entry:
            catalog[code] = {"name_zh": entry[0], "definition_zh": entry[1]}
            retained_entries += 1
        elif isinstance(previous.get(code), dict) and str(previous[code].get("name_zh") or "").strip():
            catalog[code] = {
                "name_zh": previous[code]["name_zh"],
                "definition_zh": str(previous[code].get("definition_zh") or ""),
            }
            retained_entries += 1

    top_events = sum(n for _code, n in ranked)
    new_entries = sum(1 for code, _n in ranked if code not in previous)
    report = {
        "top_n": limit,
        "ranked_codes": len(ranked),
        "codes": len(catalog),
        "missing_translations": missing,
        "top_events": top_events,
        "activity_events": activity_total,
        "top_share": round(top_events / activity_total, 4) if activity_total else 0.0,
        "reviewed_entries": reviewed_entries,
        "reviewed_events": reviewed_events,
        "extended_entries": extended_entries,
        "extended_events": extended_events,
        "new_entries": new_entries,
        "retained_entries": retained_entries,
        "previous_entries": len(previous),
    }
    return catalog, report


def build_families(db) -> dict:
    """Regenerate ``config/product_families.json`` from the product-code table."""
    return families.build_families(db, write=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", default=str(DEFAULT_DB))
    parser.add_argument("--top", type=int, default=TOP_N)
    args = parser.parse_args(argv)

    existing = read_json(CATALOG_FILE) or {}
    with open_facts(args.db) as db:
        family_payload = build_families(db)
        catalog, report = build_catalog(db, limit=args.top, existing=existing)

    write_json(CATALOG_FILE, catalog)
    changed = json.dumps(existing, ensure_ascii=False, sort_keys=True) != json.dumps(
        catalog, ensure_ascii=False, sort_keys=True
    )

    print("=" * 72)
    print("产品族（product_families.json）")
    print("=" * 72)
    print(families.coverage_report(family_payload))
    print()
    print("=" * 72)
    print(f"中文产品目录（product_catalog_zh.json，top {report['top_n']} 产品码）")
    print("=" * 72)
    print("排序口径              510(k) + 材料级 PMA（同 analyze._is_material_pma）")
    print(
        f"top-{report['top_n']} 覆盖率       {report['top_events']}/{report['activity_events']} "
        f"= {report['top_share'] * 100:.1f}%  （按新口径）"
    )
    print(f"文件条目数            {report['codes']}（上一版 {report['previous_entries']}）")
    print(f"新增条目              {report['new_entries']}（新进入 top-{report['top_n']} 的码）")
    print(f"保留条目              {report['retained_entries']}（掉出 top-{report['top_n']} 但保留）")
    print(f"已人工翻译（已审核）  {report['reviewed_entries']} 条（覆盖 {report['reviewed_events']} 条事件）")
    print(f"已人工翻译（扩展）    {report['extended_entries']} 条（覆盖 {report['extended_events']} 条事件）")
    if report["missing_translations"]:
        print(f"[warn] 缺少中文翻译 {len(report['missing_translations'])} 个产品码，已回退英文 device_name：")
        print("       " + ", ".join(report["missing_translations"][:40]))
    else:
        print("所有 top 产品码均有中文名与中文用途。")
    print(f"写入 {CATALOG_FILE}（{'已更新' if changed else '内容未变'}）")
    return 0


