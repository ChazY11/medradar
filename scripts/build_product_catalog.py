def _top_codes(db, limit: int) -> list[tuple[str, int]]:
    """Product codes by event volume (ties broken by code for determinism)."""
    rows = db.query(
        "SELECT product_code, COUNT(*) AS n FROM events"
        " WHERE product_code IS NOT NULL AND product_code != ''"
        " GROUP BY product_code ORDER BY n DESC, product_code ASC"
    )
    valid = []
    for row in rows:
        code = str(row["product_code"])
        if code.strip().upper() in families.INVALID_PRODUCT_CODES:
            continue
        if not code.replace("-", "").isalnum():  # "N/A"-style junk
            continue
        valid.append((code, int(row["n"])))
    return valid[:limit]


def build_catalog(db, limit: int = TOP_N) -> tuple[dict, dict]:
    """Build the Chinese catalog payload plus a coverage report."""
    top = _top_codes(db, limit)
    rows = db.query(
        "SELECT product_code, device_name, definition, specialty FROM product_codes"
    )
    meta = {str(row["product_code"]): row for row in rows}
    coded_rows = db.query(
        "SELECT product_code, COUNT(*) AS n FROM events"
        " WHERE product_code IS NOT NULL AND product_code != '' GROUP BY product_code"
    )
    events_total = sum(
        int(row["n"])
        for row in coded_rows
        if str(row["product_code"]).strip().upper() not in families.INVALID_PRODUCT_CODES
        and str(row["product_code"]).replace("-", "").isalnum()
    )
    catalog: dict[str, dict[str, str]] = {}
    missing: list[str] = []
    translated_events = 0
    for code, n in top:
        entry = CATALOG.get(code)
        if entry:
            name_zh, definition_zh = entry
            translated_events += n
        else:
            missing.append(code)
            name_zh = str(meta.get(code, {}).get("device_name") or code)
            definition_zh = "（暂无中文说明）" + name_zh
        catalog[code] = {"name_zh": name_zh, "definition_zh": definition_zh}
    report = {
        "top_n": limit,
        "codes": len(catalog),
        "missing_translations": missing,
        "top_events": sum(n for _c, n in top),
        "coded_events": events_total,
        "top_share": round(sum(n for _c, n in top) / events_total, 4) if events_total else 0.0,
        "translated_events": translated_events,
    }
    return catalog, report


def build_families(db) -> dict:
    """Regenerate ``config/product_families.json`` from the product-code table."""
    return families.build_families(db, write=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", default=str(DEFAULT_DB))
    parser.add_argument("--top", type=int, default=TOP_N)
    args = parser.parse_args(argv)

    with open_facts(args.db) as db:
        family_payload = build_families(db)
        catalog, report = build_catalog(db, limit=args.top)

    existing = read_json(CATALOG_FILE) or {}
    write_json(CATALOG_FILE, catalog)
    changed = json.dumps(existing, ensure_ascii=False, sort_keys=True) != json.dumps(
        catalog, ensure_ascii=False, sort_keys=True
    )

    print("=" * 72)
    print("产品族（product_families.json）")
    print("=" * 72)
    print(families.coverage_report(family_payload))
    print()
    print("=" * 72)
    print(f"中文产品目录（product_catalog_zh.json，top {report['top_n']} 产品码）")
    print("=" * 72)
    print(f"条目数                {report['codes']}")
    print(
        f"覆盖事件              {report['top_events']}/{report['coded_events']} "
        f"= {report['top_share'] * 100:.1f}%  （有产品码的事件）"
    )
    print(f"已人工翻译            {report['codes'] - len(report['missing_translations'])} 条"
          f"（覆盖 {report['translated_events']} 条事件）")
    if report["missing_translations"]:
        print(f"[warn] 缺少中文翻译 {len(report['missing_translations'])} 个产品码，已回退英文 device_name：")
        print("       " + ", ".join(report["missing_translations"][:40]))
    else:
        print("所有 top 产品码均有中文名与中文用途。")
    print(f"写入 {CATALOG_FILE}（{'已更新' if changed else '内容未变'}）")
    return 0


