"""Measure the admission rules against the independent, human-labelled evaluation set.

The evaluation set is not generated by the rules: ``config/radar/quality_eval.json`` holds
hand-written labels for a fixed-seed, stratified sample of the production ledger. This script
runs the current rules over those same observation ids and reports precision, recall and the
per-source and per-stratum breakdown, plus the composition of the default feed.

Usage (read-only, run against a real ledger):

    python scripts/evaluate_relevance.py --data-dir /srv/medradar/data/radar --json out.json
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from collections import Counter
from pathlib import Path

from medradar.radar.relevance import (
    ADMISSION_VERSION,
    HIGH_RELEVANCE,
    IRRELEVANT,
    LOW_RELEVANCE,
    NEEDS_REVIEW,
    classify_observation,
)

CONFIG = Path(__file__).resolve().parents[1] / "config" / "radar"


def load_ledger_rows(db: Path) -> dict[str, dict]:
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    facets: dict[str, dict[str, list[str]]] = {}
    for row in con.execute("SELECT observation_id, kind, value FROM observation_facet"):
        entry = facets.setdefault(row["observation_id"], {"topic": [], "product": [], "organization": []})
        entry.setdefault(row["kind"], []).append(row["value"])
    rows: dict[str, dict] = {}
    for row in con.execute(
        """SELECT o.observation_id, o.source, o.record_type, o.title, o.published_at,
                  o.first_observed_at, v.payload
           FROM observation o JOIN observation_version v ON v.version_id = o.latest_version_id"""
    ):
        payload = json.loads(row["payload"])
        mapped = facets.get(row["observation_id"], {})
        admission = classify_observation(
            {"record_type": row["record_type"], "title": row["title"], "payload": payload},
            mapped_topics=mapped.get("topic"), mapped_products=mapped.get("product"),
        )
        rows[row["observation_id"]] = {
            "observation_id": row["observation_id"],
            "source": row["source"],
            "record_type": row["record_type"],
            "title": row["title"],
            "published_at": row["published_at"],
            "engine_tier": admission.tier,
            "engine_category": admission.category,
            "engine_score": admission.score,
            "engine_reasons": admission.reasons,
        }
    con.close()
    return rows


def evaluate(eval_path: Path, rows: dict[str, dict], *, feed_limit: int = 20) -> dict:
    spec = json.loads(eval_path.read_text(encoding="utf-8"))
    items = spec["items"]
    labelled = [item for item in items if item["label"] in ("relevant", "irrelevant")]
    missing = [item["observation_id"] for item in items if item["observation_id"] not in rows]

    relevant = [item for item in labelled if item["label"] == "relevant"]
    irrelevant = [item for item in labelled if item["label"] == "irrelevant"]
    true_positive = [item for item in relevant if rows[item["observation_id"]]["engine_tier"] == HIGH_RELEVANCE]
    false_positive = [item for item in irrelevant if rows[item["observation_id"]]["engine_tier"] == HIGH_RELEVANCE]
    false_negative = [item for item in relevant if rows[item["observation_id"]]["engine_tier"] != HIGH_RELEVANCE]
    true_negative = [item for item in irrelevant if rows[item["observation_id"]]["engine_tier"] != HIGH_RELEVANCE]

    precision = len(true_positive) / (len(true_positive) + len(false_positive)) if (
        len(true_positive) + len(false_positive)) else None
    recall = len(true_positive) / len(relevant) if relevant else None

    by_source: dict[str, dict[str, int]] = {}
    for item in labelled:
        source = rows[item["observation_id"]]["source"]
        bucket = by_source.setdefault(source, {"relevant": 0, "high_hits": 0, "irrelevant": 0,
                                               "wrong_high": 0})
        if item["label"] == "relevant":
            bucket["relevant"] += 1
            if rows[item["observation_id"]]["engine_tier"] == HIGH_RELEVANCE:
                bucket["high_hits"] += 1
        else:
            bucket["irrelevant"] += 1
            if rows[item["observation_id"]]["engine_tier"] == HIGH_RELEVANCE:
                bucket["wrong_high"] += 1

    by_stratum: dict[str, dict[str, int]] = {}
    for item in items:
        stratum = item.get("stratum") or "unstratified"
        bucket = by_stratum.setdefault(stratum, {"n": 0, "relevant": 0, "high": 0})
        bucket["n"] += 1
        if item["label"] == "relevant":
            bucket["relevant"] += 1
        if rows[item["observation_id"]]["engine_tier"] == HIGH_RELEVANCE:
            bucket["high"] += 1

    tier_of_label = Counter((item["label"], rows[item["observation_id"]]["engine_tier"])
                            for item in labelled)

    # What the default feed would show: HIGH relevance, published inside a 14-day window, newest
    # first, one row per work.
    from datetime import datetime, timedelta, timezone

    cutoff = (datetime.now(timezone.utc) - timedelta(days=14)).isoformat().replace("+00:00", "Z")
    feed = sorted(
        [row for row in rows.values()
         if row["engine_tier"] == HIGH_RELEVANCE and (row["published_at"] or "") >= cutoff],
        key=lambda row: row["published_at"] or "", reverse=True,
    )
    seen_titles: set[str] = set()
    feed_unique = []
    for row in feed:
        key = " ".join((row["title"] or "").lower().split())
        if key in seen_titles:
            continue
        seen_titles.add(key)
        feed_unique.append(row)

    return {
        "admission_version": ADMISSION_VERSION,
        "eval_version": spec["version"],
        "population": spec["sample"]["population"],
        "sample_size": len(items),
        "labelled": len(labelled),
        "boundary_excluded": len(items) - len(labelled),
        "missing_from_ledger": missing,
        "confusion": {
            "relevant_high": len(true_positive),
            "relevant_not_high": len(false_negative),
            "irrelevant_high": len(false_positive),
            "irrelevant_not_high": len(true_negative),
        },
        "precision_high": precision,
        "recall_high": recall,
        "by_source": by_source,
        "by_stratum": by_stratum,
        "label_by_engine_tier": {f"{label}:{tier}": count for (label, tier), count in tier_of_label.items()},
        "false_negatives": [
            {"observation_id": item["observation_id"], "title": rows[item["observation_id"]]["title"],
             "engine_tier": rows[item["observation_id"]]["engine_tier"],
             "engine_category": rows[item["observation_id"]]["engine_category"],
             "rationale": item["rationale"]}
            for item in false_negative
        ],
        "false_positives": [
            {"observation_id": item["observation_id"], "title": rows[item["observation_id"]]["title"],
             "engine_category": rows[item["observation_id"]]["engine_category"],
             "rationale": item["rationale"]}
            for item in false_positive
        ],
        "default_feed": {
            "window_days": 14,
            "count": len(feed_unique),
            "top": [
                {"observation_id": row["observation_id"], "title": row["title"],
                 "source": row["source"], "published_at": row["published_at"],
                 "category": row["engine_category"]}
                for row in feed_unique[:feed_limit]
            ],
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", required=True)
    parser.add_argument("--eval", default=str(CONFIG / "quality_eval.json"))
    parser.add_argument("--json", default="")
    parser.add_argument("--feed-limit", type=int, default=20)
    args = parser.parse_args()
    rows = load_ledger_rows(Path(args.data_dir) / "radar.db")
    report = evaluate(Path(args.eval), rows, feed_limit=args.feed_limit)
    text = json.dumps(report, ensure_ascii=False, indent=2)
    if args.json:
        Path(args.json).write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
