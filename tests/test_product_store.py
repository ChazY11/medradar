def test_radar_track_detail_and_entrants():
    detail = store.radar_track("respiratory", 10)
    assert detail["track"]["name_zh"] == "呼吸与麻醉"
    assert detail["series"]["approvals"]
    assert detail["companies"]
    assert detail["events"]
    attribution = detail["attribution"]
    assert attribution["attributed_recent"] == sum(row["n"] for row in detail["companies"])
    assert attribution["unattributed_recent"] >= 0
    assert attribution["attributed_recent"] + attribution["unattributed_recent"] == detail["totals"]["recent"]
    assert detail["series"]["approvals"][-1]["partial"] is True, "data-edge quarter must be partial"
    for entrant in detail["entrants"]:
        assert entrant["first_date"]
        assert detail["window"]["start"] <= entrant["first_date"] <= detail["window"]["end"]


