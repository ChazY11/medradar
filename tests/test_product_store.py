"""Tests for the MedRadar 2.0 measurement layer.

These read the real research store at ``data/medradar.sqlite`` (regenerated by
``python -m medradar run``). The store is gitignored, so the whole module skips
cleanly on a fresh checkout / CI where the data has not been built yet.
"""
from __future__ import annotations

import pytest

from medradar.product import entities, store
from medradar.product.catalog import FEATURED_KEYS, METRICS, RADAR_DOMAINS

pytestmark = pytest.mark.skipif(
    not store.dataset_signature().get("exists"),
    reason="research store data/medradar.sqlite not built (run: python -m medradar run)",
)

FIVE = ["medtronic", "ge_healthcare", "philips", "draeger", "mindray"]


def test_dataset_meta_is_real():
    meta = store.dataset_meta()
    assert meta["dataset"]["counts"]["events"] > 300_000
    assert meta["dataset"]["counts"]["tracks"] >= 50
    assert meta["dataset"]["date_range"]["last"]
    dataset = meta["dataset"]
    assert dataset["track_mapped_events"] + dataset["track_unmapped_events"] == dataset["counts"]["events"]
    assert dataset["attributed_events"] + dataset["unattributed_events"] == dataset["counts"]["events"]
    assert dataset["track_unmapped_events"] != dataset["unattributed_events"]
    assert 0 < meta["dataset"]["track_mapping_coverage"] < 1
    assert len(meta["sources"]) >= 5
    assert meta["product"]["version"].startswith("2.0")
    assert any("美国" in item["text_zh"] for item in meta["limitations"])


def test_featured_roster_contains_five_firms_and_alias_firms():
    roster = entities.roster()
    for key in FEATURED_KEYS:
        assert key in roster, key
    assert roster["draeger"]["roster_present"] is False
    assert roster["mindray"]["roster_present"] is False
    assert len(entities.alias_payload()["companies"]["draeger"]["accept_exact"]) >= 20


def test_company_list_has_real_counts_for_five_firms():
    rows = {row["key"]: row for row in store.company_list()}
    for key in FIVE:
        assert key in rows, key
        assert rows[key]["events"] > 100, key
        assert rows[key]["approvals"] > 0, key
    assert rows["medtronic"]["featured"] is True
    assert rows["draeger"]["roster_present"] is False


@pytest.mark.parametrize("key", FIVE)
def test_company_profile_claims_are_evidence_linked_and_recomputable(key: str):
    profile = store.company_profile(key, 5)
    assert profile["headline"]["events_all_time"] > 0
    assert profile["headline"]["approvals_window_all"] >= profile["headline"]["approvals_window"]
    assert profile["headline"]["unmapped_window"] >= 0
    assert profile["headline"]["pathway_mix"]["basis"] == "window_approvals_only"
    assert profile["headline"]["pathway_mix_all_time"]["basis"] == "all_time_approvals_only"
    assert profile["headline"]["pma_original_window"] + profile["headline"]["pma_supplement_window"] <= profile["headline"]["approvals_window_all"]
    assert profile["coverage"], key
    assert profile["tracks"]["rows"], key
    assert profile["claims"], f"no claims for {key}"
    claim = profile["claims"][0]
    assert claim["tier"] == "observed"
    assert claim["statement_zh"]
    assert claim["caveats"], "every claim must state its caveats"
    evidence = store.claim_evidence(claim["evidence_params"])
    assert evidence["recomputed"]["recent"] == claim["metrics"]["recent"]
    assert evidence["recomputed"]["prior"] == claim["metrics"]["prior"]
    assert evidence["recent_events"], key
    assert evidence["window"]["recent_start"] == claim["window"]["recent_start"]
    for item in evidence["recent_events"][:5]:
        assert item["event_id"]
        assert item["event_date"]


