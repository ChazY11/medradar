"""Artifact writers for SCIENCE-002: every committed number comes from here."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping, Sequence

from .sources import sha256_bytes
from .universe import write_csv

UNIVERSE_FIELDS = ("key", "cik", "ticker", "sec_title", "sic", "sic_description",
                   "tiers", "n_window_clearances", "applicants")
MATCH_FIELDS = ("cik", "sec_title", "tier", "applicant_root", "owner_root",
                "evidence", "n_window_clearances")


def write_json(path: Path, payload: Any) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = (json.dumps(payload, indent=1, sort_keys=True, default=str) + "\n").encode("utf-8")
    path.write_bytes(data)
    return sha256_bytes(data)


def payload_sha256(payload: Any) -> str:
    """Stable digest of a result payload (sorted keys, no whitespace variance)."""
    return sha256_bytes(json.dumps(payload, sort_keys=True, default=str).encode("utf-8"))


PRIMARY_KEYS = ("meta", "primary", "permutation", "permutation_circular", "conditional",
                "pooled", "bootstrap", "pooled_bootstrap", "pooled_delta_B3_minus_B2",
                "lofo", "secondary_B4", "power")


def primary_digest(result: Mapping[str, Any]) -> str:
    """Digest of the confirmatory part of a payload (everything but the placebo
    features, which are stochastic and can be switched off for fast re-runs)."""
    subset = {key: result.get(key) for key in PRIMARY_KEYS}
    return payload_sha256(subset)


def artifact_sha256(path: Path) -> str | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8")).get("_payload_sha256")


def _tier_counts(matches: Sequence[Mapping[str, Any]]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for row in matches:
        key = str(row["tier"])
        counts[key] = counts.get(key, 0) + 1
    return counts


def write_universe_artifacts(build: Any, artifacts: Path) -> dict[str, Any]:
    artifacts.mkdir(parents=True, exist_ok=True)
    universe_hash = write_csv(artifacts / "universe.csv",
                              [f.as_row() for f in build.included], UNIVERSE_FIELDS)
    match_hash = write_csv(artifacts / "entity_matches.csv", build.matches, MATCH_FIELDS)
    ledger_rows = build.excluded
    exclusion_hash = write_csv(artifacts / "entity_exclusions.csv", ledger_rows,
                               tuple(ledger_rows[0].keys()) if ledger_rows else ("cik",))
    summary = {
        **build.meta,
        "universe_sha256": universe_hash,
        "entity_matches_sha256": match_hash,
        "entity_exclusions_sha256": exclusion_hash,
        "sic_set": sorted({f.sic for f in build.included}),
        "tier_counts": _tier_counts(build.matches),
        "n_clearances_total": sum(f.n_window_clearances for f in build.included),
        "firms": [{"key": f.key, "ticker": f.ticker, "cik": f.cik,
                   "n_window_clearances": f.n_window_clearances,
                   "tiers": f.tier_str} for f in build.included],
    }
    summary["summary_sha256"] = write_json(artifacts / "universe_summary.json", summary)
    return summary


def write_source_manifest(cache_root: Path, artifacts: Path) -> dict[str, Any]:
    """Every cached response: URL, status, bytes, SHA-256 and collection time.

    The raw bodies are not committed (size), so this manifest is the audit trail
    that lets a reader re-fetch and verify. It is regenerated by the fetch and
    universe steps.
    """
    entries = []
    for meta_path in sorted(Path(cache_root).glob("*.json")):
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if "url" not in meta or "sha256" not in meta:
            continue
        entries.append({
            "url": meta["url"], "status": meta.get("status"),
            "bytes": meta.get("bytes"), "sha256": meta["sha256"],
            "fetched_at_utc": meta.get("fetched_at_utc"),
        })
    for download_meta in sorted(Path(cache_root).glob("**/*.json")):
        if download_meta.parent == Path(cache_root):
            continue
        try:
            meta = json.loads(download_meta.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if "url" not in meta or "sha256" not in meta:
            continue
        entries.append({
            "url": meta["url"], "status": 200, "bytes": meta.get("bytes"),
            "sha256": meta["sha256"], "fetched_at_utc": meta.get("fetched_at_utc"),
            "bulk_export": True,
            "export_date": meta.get("export_date"),
        })
    payload = {"n_entries": len(entries), "entries": entries}
    payload["manifest_sha256"] = write_json(Path(artifacts) / "source_manifest.json", payload)
    return payload


def write_panel_artifacts(panel_result: Any, build: Any, artifacts: Path) -> dict[str, Any]:
    artifacts.mkdir(parents=True, exist_ok=True)
    fields = ("key", "ticker", "month_end", "split", "label", "n_events_in_window",
              "label_507", "label_any8k")
    feature_names = sorted({name for row in panel_result.rows for name in row.features})
    rows = [{**{f: getattr(row, f) for f in fields},
             **{name: row.features.get(name) for name in feature_names}}
            for row in panel_result.rows]
    panel_hash = write_csv(artifacts / "panel.csv", rows, fields + tuple(feature_names))
    meta = {**panel_result.meta, "panel_sha256": panel_hash,
            "feature_names": feature_names}
    meta["summary_sha256"] = write_json(artifacts / "panel_summary.json", meta)
    return meta


def write_experiment_artifacts(result: Mapping[str, Any], panel_result: Any,
                               artifacts: Path) -> dict[str, Any]:
    artifacts.mkdir(parents=True, exist_ok=True)
    payload = {"_payload_sha256": payload_sha256(result), **result}
    return {"path": str(artifacts / "experiment_results.json"),
            "sha256": write_json(artifacts / "experiment_results.json", payload)}


def write_audit_artifacts(result: Mapping[str, Any], artifacts: Path) -> dict[str, Any]:
    artifacts.mkdir(parents=True, exist_ok=True)
    return {"path": str(artifacts / "audit_results.json"),
            "sha256": write_json(artifacts / "audit_results.json", result)}