#!/usr/bin/env python3
"""Prove the consistency gate turns green once the prose quotes the official run.

The frozen HORIZON prose cannot be edited from this workstream (it is a frozen
input).  This script therefore splices the proposed corrected EXP-H2 sections into
temporary copies of the two documents and runs the real gate against the real pair
file, the real summary, and those temporary documents.

Usage:
    python research/convergence/h2/verify_corrected_prose.py
"""

from __future__ import annotations

import importlib.util
import os
import tempfile

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                         "..", "..", ".."))
EXP_DOC = os.path.join(REPO_ROOT, "research", "horizon", "EXPERIMENT_RESULTS.md")
REPORT_DOC = os.path.join(REPO_ROOT, "research", "horizon", "reports",
                          "REGULATORY_FRONTIER_REPORT.md")
PAIRS = os.path.join(REPO_ROOT, "research", "horizon", "experiments", "regulatory",
                     "EXP_H2_PAIRS.jsonl")
SUMMARY = os.path.join(REPO_ROOT, "research", "horizon", "experiments", "regulatory",
                       "EXP_H2_SUMMARY.json")
GATE = os.path.join(REPO_ROOT, "tools", "convergence", "h2",
                    "check_h2_consistency.py")

EXP_SECTION = """## EXP-H2 — cross-national product identity quality

**Files:** `experiments/regulatory/EXP_H2_SELECTION_RULE.md` (written before any pair
was examined), `EXP_H2_PAIRS.jsonl` (726 pairs), `EXP_H2_SUMMARY.json`,
`exp_h2_identity.py`. Inputs: 320 FDA GUDID records × 174 Health Canada MDALL records.

Signals, in increasing strength:
**S1** exact name · **S2** shared model token · **S3** same firm ·
**S4** shared official identifier · **S5** name-token overlap ≥2.

### Result: 726 pairs, 0 CONFIRMED

| verdict | n |
|---|---|
| `CONFIRMED` | **0** |
| `REJECTED` | 0 |
| `UNKNOWN` | 726 |

**`S4_official_identifier_fired: 0`.** GUDID and MDALL share **no identifier
namespace** — UDI-DI versus Health Canada licence / device / identifier numbers. There
is therefore **no keyless official-identifier bridge between the two registries**.

Signal sufficiency table (the deliverable, not a footnote):

| signal combination | pairs | CONFIRMED | REJECTED | UNKNOWN | reaches CONFIRMED? |
|---|---|---|---|---|---|
| S3 + S5 | 19 | 0 | 0 | 19 | no |
| S3 | 689 | 0 | 0 | 689 | no |
| S5 | 18 | 0 | 0 | 18 | no |
| S2 (shared model token) | 0 fired | 0 | 0 | 0 | no |
| S3 (same firm) | 708 fired | 0 | 0 | 708 | no |

Hard negatives: **26 pairs** constructed by the stated rules
(`HN3_same_family_different_device` 14, `HN4_subsidiary_vs_parent` 12); all 26 land in
`UNKNOWN`, which is the correct outcome — the point of a hard negative is that it must
not be silently matched.
"""

REPORT_SECTION = """## 5. EXP-H2 — can a US and a Canadian record be shown to be the same product?

726 pairs were generated from 320 GUDID × 174 MDALL records against a pre-registered
selection rule, then scored on five signals of increasing strength. Of those, 700
candidate pairs were generated by pair construction and 26 pairs are constructed hard
negatives.

| verdict | n |
|---|---|
| **CONFIRMED** | **0** |
| REJECTED | 0 |
| UNKNOWN | 726 |

**`S4_official_identifier_fired = 0`.**

| signal combination | pairs | CONFIRMED | REJECTED | UNKNOWN |
|---|---|---|---|---|
| S3 + S5 | 19 | 0 | 0 | 19 |
| S3 | 689 | 0 | 0 | 689 |
| S5 | 18 | 0 | 0 | 18 |
| S2 alone (shared model token, 0 fired) | — | 0 | 0 | 0 |
| S3 alone (same firm, 708 fired) | — | 0 | 0 | 708 |

Hard negatives: 26 pairs (14 `HN3_same_family_different_device`, 12
`HN4_subsidiary_vs_parent`); all 26 land in `UNKNOWN`, which is the correct outcome —
the purpose of a hard negative is that it must not be silently matched.

"""


def _load_gate():
    spec = importlib.util.spec_from_file_location("h2_gate_verify", GATE)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def _splice(lines, start_pred, stop_pred, replacement):
    start = next(i for i, line in enumerate(lines) if start_pred(line))
    stop = next(j for j in range(start + 1, len(lines)) if stop_pred(lines[j]))
    return lines[:start] + replacement.splitlines() + lines[stop:]


def main():
    with open(EXP_DOC, "r", encoding="utf-8") as fh:
        exp_lines = fh.read().splitlines()
    with open(REPORT_DOC, "r", encoding="utf-8") as fh:
        rep_lines = fh.read().splitlines()

    # EXPERIMENT_RESULTS: replace from the H2 heading through the hard-negative
    # paragraph; the "What this means for MedRadar" discussion is preserved.
    def exp_stop(line):
        return line.startswith("### What this means")

    exp_new = _splice(exp_lines, lambda l: l.startswith("## EXP-H2"),
                      exp_stop, EXP_SECTION)
    # The preserved "What this means" discussion also quotes the stale 445.
    exp_text = "\n".join(exp_new)
    exp_text = exp_text.replace(
        'here and would have been meaningless: 445 pairs share a model token, 0 are\n'
        '   provable.',
        'here and would have been meaningless: the strict model-token rule fires 0\n'
        '   times on this sample, and no pair is provable from name-level evidence.')
    exp_new = exp_text.splitlines()
    # REPORT: replace from the section heading up to "### The finding".
    rep_new = _splice(rep_lines, lambda l: l.startswith("## 5. EXP-H2"),
                      lambda l: l.startswith("### The finding"), REPORT_SECTION)

    gate = _load_gate()
    with tempfile.TemporaryDirectory(prefix="h2-corrected-") as tmp:
        exp_path = os.path.join(tmp, "EXPERIMENT_RESULTS.md")
        rep_path = os.path.join(tmp, "REGULATORY_FRONTIER_REPORT.md")
        with open(exp_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(exp_new) + "\n")
        with open(rep_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(rep_new) + "\n")
        result = gate.evaluate(PAIRS, SUMMARY, exp_path, rep_path)

    print("gate against the real artifacts + proposed corrected prose")
    print(f"  checks={len(result['checks'])} "
          f"mismatches={len(result['mismatches'])} errors={len(result['errors'])}")
    for mismatch in result["mismatches"]:
        print(f"  MISMATCH {mismatch['name']}: {mismatch['actual']!r} != "
              f"{mismatch['expected']!r} ({mismatch['location']})")
    for error in result["errors"]:
        print(f"  EXTRACT {error['doc']}: {error['message']}")
    print("RESULT:", result["status"].upper())
    return result["exit_code"]


if __name__ == "__main__":
    raise SystemExit(main())
